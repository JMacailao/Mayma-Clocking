-- Uppercase hex with separators removed, or NULL when it is not a 12-digit serial.
CREATE OR REPLACE FUNCTION public.normalize_device_serial(p_serial text)
RETURNS text LANGUAGE sql IMMUTABLE SET search_path = '' AS $$
  SELECT CASE WHEN s ~ '^[0-9A-F]{12}$' THEN s END
  FROM (SELECT upper(regexp_replace(coalesce(p_serial, ''), '[\s:.-]', '', 'g')) AS s) AS cleaned
$$;

CREATE OR REPLACE FUNCTION public._rfid_device_key_hash(p_key text)
RETURNS bytea LANGUAGE sql IMMUTABLE SET search_path = '' AS $$
  SELECT sha256(convert_to(upper(regexp_replace(coalesce(p_key, ''), '[\s-]', '', 'g')), 'UTF8'))
$$;
REVOKE ALL ON FUNCTION public._rfid_device_key_hash(text) FROM PUBLIC, anon, authenticated;

-- 32 random hex characters (122 bits) from the server's secure random source.
CREATE OR REPLACE FUNCTION public._new_rfid_device_key()
RETURNS text LANGUAGE sql VOLATILE SET search_path = '' AS $$
  SELECT upper(replace(gen_random_uuid()::text, '-', ''))
$$;
REVOKE ALL ON FUNCTION public._new_rfid_device_key() FROM PUBLIC, anon, authenticated;

