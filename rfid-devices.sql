-- AvilonX Clocking: external RFID readers (ESP8266 + RC522).
--
-- The Super Admin registers each reader by its serial number (the board's
-- Wi-Fi MAC address), assigns it to a club and gets a device key. The reader sends every tag it reads,
-- with its serial and key, to public.device_rfid_scan(). Readers that are not
-- registered, or send the wrong key, are refused.
--
-- Each reader has a mode:
--   register  every tap is passed to the Race entries and Register NFC pages,
--             which fill the NFC tag field with it.
--   clock     every tap clocks that tag's pigeon in an open race of the club,
--             at Supabase server time, like a member tapping the tag.
-- The club's admin or staff choose the mode, and can tie a reader to one member
-- (a loft clock) so it only clocks that member's pigeons. Only the Super Admin
-- can register, move, re-key or delete readers.
--
-- Run after nfc-tags.sql. Safe to run again.

DO $$
BEGIN
  IF to_regprocedure('public.normalize_nfc_uid(text)') IS NULL
     OR to_regprocedure('public._clock_receipt_details(bigint,bigint)') IS NULL THEN
    RAISE EXCEPTION 'Run nfc-tags.sql (and sticker-barcodes.sql) before rfid-devices.sql.';
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS public.rfid_devices (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  club_id bigint NOT NULL REFERENCES public.clubs(id) ON DELETE CASCADE,
  serial varchar(12) COLLATE "C" NOT NULL UNIQUE CHECK (serial ~ '^[0-9A-F]{12}$'),
  name text NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 80),
  member_id bigint REFERENCES public.members(id) ON DELETE SET NULL,
  mode text NOT NULL DEFAULT 'register' CHECK (mode IN ('register', 'clock')),
  key_hash bytea NOT NULL,
  last_seen_at timestamptz,
  last_tag varchar(20),
  created_by uuid,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_rfid_devices_club ON public.rfid_devices(club_id);

CREATE TABLE IF NOT EXISTS public.rfid_device_scans (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_id bigint NOT NULL REFERENCES public.rfid_devices(id) ON DELETE CASCADE,
  tag_uid varchar(20) NOT NULL,
  mode text NOT NULL,
  result text,
  scanned_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_rfid_device_scans_device ON public.rfid_device_scans(device_id, id);
CREATE INDEX IF NOT EXISTS idx_rfid_device_scans_time ON public.rfid_device_scans(scanned_at);

-- Everything goes through the functions below; the key hash is never readable.
ALTER TABLE public.rfid_devices ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.rfid_device_scans ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.rfid_devices, public.rfid_device_scans FROM PUBLIC, anon, authenticated;

-- Uppercase hex with separators removed, or NULL when it is not a 12-digit serial.
CREATE OR REPLACE FUNCTION public.normalize_device_serial(p_serial text)
RETURNS text LANGUAGE sql IMMUTABLE SET search_path = '' AS $$
  SELECT CASE WHEN s ~ '^[0-9A-F]{12}$' THEN s END
  FROM (SELECT upper(regexp_replace(coalesce(p_serial, ''), '[\s:.-]', '', 'g')) AS s) AS cleaned
$$;

CREATE OR REPLACE FUNCTION public._rfid_device_key_hash(p_key text)
RETURNS bytea LANGUAGE sql IMMUTABLE SET search_path = '' AS $$
  SELECT sha256(convert_to(upper(regexp_replace(coalesce(p_key, ''), '[\s-]', '', 'g')), 'UTF8'))
$$;
REVOKE ALL ON FUNCTION public._rfid_device_key_hash(text) FROM PUBLIC, anon, authenticated;

-- 32 random hex characters (122 bits) from the server's secure random source.
CREATE OR REPLACE FUNCTION public._new_rfid_device_key()
RETURNS text LANGUAGE sql VOLATILE SET search_path = '' AS $$
  SELECT upper(replace(gen_random_uuid()::text, '-', ''))
$$;
REVOKE ALL ON FUNCTION public._new_rfid_device_key() FROM PUBLIC, anon, authenticated;

-- Club admin: list this club's readers.
CREATE OR REPLACE FUNCTION public.admin_list_rfid_devices()
RETURNS TABLE (id bigint, serial text, name text, member_id bigint, member_name text, mode text, last_seen_at timestamptz, last_tag text, created_at timestamptz)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = '' AS $$
BEGIN
  IF NOT public.can_manage_club_data() THEN RAISE EXCEPTION 'Club administrator or staff account required.' USING ERRCODE = '42501'; END IF;
  RETURN QUERY
    SELECT d.id, d.serial::text, d.name, d.member_id, m.full_name::text, d.mode, d.last_seen_at, d.last_tag::text, d.created_at
    FROM public.rfid_devices AS d LEFT JOIN public.members AS m ON m.id = d.member_id
    WHERE d.club_id = public.current_club_id()
    ORDER BY d.created_at DESC;
END;
$$;

CREATE OR REPLACE FUNCTION public._check_rfid_device_member(p_member_id bigint)
RETURNS void LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = '' AS $$
BEGIN
  IF p_member_id IS NOT NULL AND NOT EXISTS (SELECT 1 FROM public.members AS m WHERE m.id = p_member_id AND m.club_id = public.current_club_id()) THEN
    RAISE EXCEPTION 'That member is not in your club.' USING ERRCODE = '22023';
  END IF;
END;
$$;
REVOKE ALL ON FUNCTION public._check_rfid_device_member(bigint) FROM PUBLIC, anon, authenticated;

-- Club admin: change a reader's name, member or mode.
CREATE OR REPLACE FUNCTION public.admin_update_rfid_device(p_id bigint, p_name text, p_member_id bigint, p_mode text)
RETURNS void LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path = '' AS $$
BEGIN
  IF NOT public.can_manage_club_data() THEN RAISE EXCEPTION 'Club administrator or staff account required.' USING ERRCODE = '42501'; END IF;
  IF coalesce(btrim(p_name), '') = '' THEN RAISE EXCEPTION 'Give the reader a name.' USING ERRCODE = '22023'; END IF;
  IF p_mode NOT IN ('register', 'clock') THEN RAISE EXCEPTION 'Choose Register or Clocking mode.' USING ERRCODE = '22023'; END IF;
  PERFORM public._check_rfid_device_member(p_member_id);
  UPDATE public.rfid_devices AS d SET name = btrim(p_name), member_id = p_member_id, mode = p_mode
  WHERE d.id = p_id AND d.club_id = public.current_club_id();
  IF NOT FOUND THEN RAISE EXCEPTION 'Reader not found.' USING ERRCODE = '22023'; END IF;
END;
$$;

