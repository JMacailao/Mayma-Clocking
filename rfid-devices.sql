-- AvilonX Clocking: external RFID readers (ESP8266 + RC522).
--
-- The Super Admin registers each reader by its serial number (the board's
-- Wi-Fi MAC address), assigns it to a club and gets a device key. The reader sends every tag it reads,
-- with its serial and key, to public.device_rfid_scan(). Readers that are not
-- registered, or send the wrong key, are refused.
--
-- Each reader has a mode:
--   register  every tap is passed to the Race entries and Register NFC pages,
--             which fill the NFC tag field with it.
--   clock     every tap clocks that tag's pigeon in an open race of the club,
--             at Supabase server time, like a member tapping the tag.
-- The mode follows from who uses the reader, chosen by the Super Admin (the
-- only one who can register, move, re-key or delete readers):
--   the club admin  -> register only (never clocks)
--   one member      -> clock only, and only that member's own pigeons' tags
--
-- Run after nfc-tags.sql. Safe to run again.

DO $$
BEGIN
  IF to_regprocedure('public.normalize_nfc_uid(text)') IS NULL
     OR to_regprocedure('public._clock_receipt_details(bigint,bigint)') IS NULL THEN
    RAISE EXCEPTION 'Run nfc-tags.sql (and sticker-barcodes.sql) before rfid-devices.sql.';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'race_entries' AND column_name = 'nfc_expires_at') THEN
    RAISE EXCEPTION 'Run the latest nfc-tags.sql first (it adds the RFID tag expiry), then rfid-devices.sql.';
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS public.rfid_devices (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  club_id bigint NOT NULL REFERENCES public.clubs(id) ON DELETE CASCADE,
  serial varchar(12) COLLATE "C" NOT NULL UNIQUE CHECK (serial ~ '^[0-9A-F]{12}$'),
  name text NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 80),
  member_id bigint REFERENCES public.members(id) ON DELETE SET NULL,
  mode text NOT NULL DEFAULT 'register' CHECK (mode IN ('register', 'clock')),
  key_hash bytea NOT NULL,
  last_seen_at timestamptz,
  last_tag varchar(20),
  created_by uuid,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_rfid_devices_club ON public.rfid_devices(club_id);

-- A reader's job follows from who uses it:
--   club admin (no member)  -> register: taps fill the Race entries tag field, never clock
--   one member (loft clock) -> clock: taps clock only that member's own pigeons, never register
-- The trigger keeps mode in step on every change (also when a member is deleted
-- and member_id is cleared).
CREATE OR REPLACE FUNCTION public._rfid_device_mode_from_member()
RETURNS trigger LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
  NEW.mode := CASE WHEN NEW.member_id IS NULL THEN 'register' ELSE 'clock' END;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS rfid_devices_mode_from_member ON public.rfid_devices;
CREATE TRIGGER rfid_devices_mode_from_member BEFORE INSERT OR UPDATE ON public.rfid_devices
  FOR EACH ROW EXECUTE FUNCTION public._rfid_device_mode_from_member();
UPDATE public.rfid_devices SET mode = mode;  -- bring readers saved earlier into line

