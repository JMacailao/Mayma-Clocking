-- Super Admin: every reader with its club.
CREATE OR REPLACE FUNCTION public.superadmin_list_rfid_devices()
RETURNS TABLE (id bigint, serial text, name text, club_id bigint, club_name text, member_name text, mode text, last_seen_at timestamptz, last_tag text, created_at timestamptz)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = '' AS $$
BEGIN
  PERFORM public._require_superadmin();
  RETURN QUERY
    SELECT d.id, d.serial::text, d.name, d.club_id, c.name::text, m.full_name::text, d.mode, d.last_seen_at, d.last_tag::text, d.created_at
    FROM public.rfid_devices AS d JOIN public.clubs AS c ON c.id = d.club_id LEFT JOIN public.members AS m ON m.id = d.member_id
    ORDER BY d.created_at DESC;
END;
$$;

-- Super Admin: register a reader for a club. Returns its key, shown only once.
CREATE OR REPLACE FUNCTION public.superadmin_register_rfid_device(p_serial text, p_name text, p_club_id bigint, p_mode text DEFAULT 'register')
RETURNS jsonb LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path = '' AS $$
DECLARE
  v_serial text := public.normalize_device_serial(p_serial);
  v_key text := public._new_rfid_device_key();
  v_id bigint;
BEGIN
  PERFORM public._require_superadmin();
  IF v_serial IS NULL THEN RAISE EXCEPTION 'Enter the reader''s 12-character serial number, for example 5C:CF:7F:12:34:56.' USING ERRCODE = '22023'; END IF;
  IF coalesce(btrim(p_name), '') = '' THEN RAISE EXCEPTION 'Give the reader a name.' USING ERRCODE = '22023'; END IF;
  IF p_mode NOT IN ('register', 'clock') THEN RAISE EXCEPTION 'Choose Register or Clocking mode.' USING ERRCODE = '22023'; END IF;
  IF NOT EXISTS (SELECT 1 FROM public.clubs AS c WHERE c.id = p_club_id) THEN RAISE EXCEPTION 'Choose the club that will use this reader.' USING ERRCODE = '22023'; END IF;
  IF EXISTS (SELECT 1 FROM public.rfid_devices AS d WHERE d.serial = v_serial) THEN
    RAISE EXCEPTION 'Reader % is already registered.', v_serial USING ERRCODE = '23505';
  END IF;
  INSERT INTO public.rfid_devices (club_id, serial, name, mode, key_hash, created_by)
  VALUES (p_club_id, v_serial, btrim(p_name), p_mode, public._rfid_device_key_hash(v_key), (SELECT auth.uid()))
  RETURNING id INTO v_id;
  RETURN jsonb_build_object('id', v_id, 'serial', v_serial, 'device_key', v_key);
END;
$$;

-- Super Admin: rename a reader or move it to another club (its member link is cleared on a move).
CREATE OR REPLACE FUNCTION public.superadmin_update_rfid_device(p_id bigint, p_name text, p_club_id bigint)
RETURNS void LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path = '' AS $$
BEGIN
  PERFORM public._require_superadmin();
  IF coalesce(btrim(p_name), '') = '' THEN RAISE EXCEPTION 'Give the reader a name.' USING ERRCODE = '22023'; END IF;
  IF NOT EXISTS (SELECT 1 FROM public.clubs AS c WHERE c.id = p_club_id) THEN RAISE EXCEPTION 'Choose the club that will use this reader.' USING ERRCODE = '22023'; END IF;
  UPDATE public.rfid_devices AS d
  SET name = btrim(p_name), member_id = CASE WHEN d.club_id = p_club_id THEN d.member_id END, club_id = p_club_id
  WHERE d.id = p_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Reader not found.' USING ERRCODE = '22023'; END IF;
END;
$$;

-- Super Admin: make a new key (the old one stops working at once).
CREATE OR REPLACE FUNCTION public.superadmin_reset_rfid_device_key(p_id bigint)
RETURNS jsonb LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path = '' AS $$
DECLARE
  v_key text := public._new_rfid_device_key();
  v_serial text;
BEGIN
  PERFORM public._require_superadmin();
  UPDATE public.rfid_devices AS d SET key_hash = public._rfid_device_key_hash(v_key) WHERE d.id = p_id RETURNING d.serial INTO v_serial;
  IF NOT FOUND THEN RAISE EXCEPTION 'Reader not found.' USING ERRCODE = '22023'; END IF;
  RETURN jsonb_build_object('id', p_id, 'serial', v_serial, 'device_key', v_key);
END;
$$;

CREATE OR REPLACE FUNCTION public.superadmin_delete_rfid_device(p_id bigint)
RETURNS void LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path = '' AS $$
BEGIN
  PERFORM public._require_superadmin();
  DELETE FROM public.rfid_devices AS d WHERE d.id = p_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Reader not found.' USING ERRCODE = '22023'; END IF;
END;
$$;

-- Tags read by Register-mode readers since p_after_id, for the pages that fill
-- in an NFC tag field. Club admins and staff see their club's readers; the
-- Super Admin (who registers tags for every club) sees all readers.
CREATE OR REPLACE FUNCTION public.rfid_recent_scans(p_after_id bigint DEFAULT NULL)
RETURNS TABLE (id bigint, device_name text, tag_uid text, scanned_at timestamptz)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = '' AS $$
DECLARE
  v_super boolean := public.is_superadmin();
BEGIN
  IF NOT v_super AND NOT public.can_manage_club_data() THEN
    RAISE EXCEPTION 'Club administrator, staff or Super Admin account required.' USING ERRCODE = '42501';
  END IF;
  RETURN QUERY
    SELECT s.id, d.name, s.tag_uid::text, s.scanned_at
    FROM public.rfid_device_scans AS s JOIN public.rfid_devices AS d ON d.id = s.device_id
    WHERE s.mode = 'register'
      AND (v_super OR d.club_id = public.current_club_id())
      AND (p_after_id IS NULL OR s.id > p_after_id)
      AND s.scanned_at > now() - interval '10 minutes'
    ORDER BY s.id DESC
    LIMIT 20;
END;
$$;

-- Called by the reader itself (no sign-in) for every tag it reads.
CREATE OR REPLACE FUNCTION public.device_rfid_scan(p_serial text, p_key text, p_tag text)
RETURNS jsonb LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path = '' AS $$
DECLARE
  v_device public.rfid_devices%ROWTYPE;
  v_uid text := public.normalize_nfc_uid(p_tag);
  v_matches integer;
  v_entry public.race_entries%ROWTYPE;
  v_race public.races%ROWTYPE;
  v_now timestamp without time zone;
  v_clock public.clock_events%ROWTYPE;
  v_result jsonb;
BEGIN
  SELECT d.* INTO v_device FROM public.rfid_devices AS d
  WHERE d.serial = public.normalize_device_serial(p_serial) FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'This reader is not registered. Ask the Super Admin to register serial %.', coalesce(public.normalize_device_serial(p_serial), p_serial) USING ERRCODE = '42501';
  END IF;
  IF v_device.key_hash <> public._rfid_device_key_hash(p_key) THEN
    RAISE EXCEPTION 'The device key is wrong. Ask the Super Admin for a new key.' USING ERRCODE = '42501';
  END IF;
  IF v_uid IS NULL THEN RAISE EXCEPTION 'The tag ID could not be read. Tap the tag again.' USING ERRCODE = '22023'; END IF;

  UPDATE public.rfid_devices AS d SET last_seen_at = now(), last_tag = v_uid WHERE d.id = v_device.id;
  DELETE FROM public.rfid_device_scans AS s WHERE s.scanned_at < now() - interval '2 days';

  IF v_device.mode = 'register' THEN
    INSERT INTO public.rfid_device_scans (device_id, tag_uid, mode, result) VALUES (v_device.id, v_uid, 'register', 'sent');
    RETURN jsonb_build_object('status', 'sent', 'mode', 'register', 'tag', v_uid,
      'message', 'Tag ' || v_uid || ' sent to the open Race entries or Register NFC page.');
  END IF;

  SELECT count(*) INTO v_matches
  FROM public.race_entries AS e JOIN public.races AS r ON r.id = e.race_id
  WHERE e.nfc_tag = v_uid AND r.status = 'open' AND r.club_id = v_device.club_id
    AND (v_device.member_id IS NULL OR e.member_id = v_device.member_id);
  IF v_matches <> 1 THEN
    v_result := jsonb_build_object('status', 'error', 'mode', 'clock', 'tag', v_uid, 'message',
      CASE WHEN v_matches = 0 THEN 'Tag ' || v_uid || ' is not on a pigeon in an open race' || CASE WHEN v_device.member_id IS NULL THEN '.' ELSE ' for this loft.' END
           ELSE 'Tag ' || v_uid || ' is entered in more than one open race. Clock it on the Clocking page.' END);
    INSERT INTO public.rfid_device_scans (device_id, tag_uid, mode, result) VALUES (v_device.id, v_uid, 'clock', v_result->>'message');
    RETURN v_result;
  END IF;

  SELECT e.* INTO v_entry
  FROM public.race_entries AS e JOIN public.races AS r ON r.id = e.race_id
  WHERE e.nfc_tag = v_uid AND r.status = 'open' AND r.club_id = v_device.club_id
    AND (v_device.member_id IS NULL OR e.member_id = v_device.member_id)
  FOR UPDATE OF e;
  SELECT r.* INTO v_race FROM public.races AS r WHERE r.id = v_entry.race_id;
  v_now := clock_timestamp() AT TIME ZONE 'UTC';

  IF v_race.release_at_utc IS NULL OR v_now <= v_race.release_at_utc THEN
    v_result := jsonb_build_object('status', 'error', 'mode', 'clock', 'tag', v_uid, 'message', v_race.name || ' has not started yet.');
  ELSE
    SELECT c.* INTO v_clock FROM public.clock_events AS c WHERE c.race_entry_id = v_entry.id;
    IF FOUND THEN
      v_result := jsonb_build_object('status', 'duplicate', 'message', 'Ring ' || v_entry.pigeon_ring || ' already has a receipt.');
    ELSE
      INSERT INTO public.clock_events (race_entry_id, pigeon_ring, received_at_utc, source, verification)
      VALUES (v_entry.id, v_entry.pigeon_ring, v_now, 'nfc', 'provisional')
      RETURNING * INTO v_clock;
      v_result := jsonb_build_object('status', 'accepted', 'message', 'Ring ' || v_entry.pigeon_ring || ' clocked for ' || v_race.name || '.');
    END IF;
    v_result := v_result || jsonb_build_object('mode', 'clock', 'tag', v_uid, 'pigeon_ring', v_entry.pigeon_ring, 'race', v_race.name,
      'received_at_utc', v_clock.received_at_utc) || COALESCE(public._clock_receipt_details(v_entry.id, v_clock.id), '{}'::jsonb);
  END IF;
  INSERT INTO public.rfid_device_scans (device_id, tag_uid, mode, result) VALUES (v_device.id, v_uid, 'clock', v_result->>'message');
  RETURN v_result;
END;
$$;

