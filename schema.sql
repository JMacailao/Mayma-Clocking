-- Mayma Clocking: Supabase Auth + PostgreSQL, static HTML/CSS/JS client.
-- Run once in Supabase SQL Editor as the project database owner.
-- Existing race data tables are preserved. This file adds app profiles and safe
-- policies; it does not remove existing rows or migrate user passwords.
BEGIN;
SET LOCAL TIME ZONE 'UTC';

-- Stop early if the earlier Firebase version was applied; run supabase-auth.sql instead.
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM information_schema.columns
             WHERE table_schema='public' AND table_name='app_profiles'
               AND column_name='id' AND data_type='text') OR to_regclass('public.clubs') IS NOT NULL THEN
    RAISE EXCEPTION 'The Firebase version was applied. Run supabase-auth.sql instead of schema.sql.';
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS public.members (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_no varchar(40) NOT NULL UNIQUE,
  full_name varchar(180) NOT NULL,
  first_name varchar(180),
  middle_name varchar(180),
  last_name varchar(180),
  loft_name varchar(180) NOT NULL,
  address varchar(500),
  phone varchar(40),
  paid smallint NOT NULL DEFAULT 0 CHECK (paid IN (0,1)),
  latitude numeric(10,7) NOT NULL CHECK (latitude BETWEEN -90 AND 90),
  longitude numeric(10,7) NOT NULL CHECK (longitude BETWEEN -180 AND 180),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.race_points (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  location varchar(180) NOT NULL,
  description varchar(500),
  sector varchar(100) NOT NULL,
  latitude numeric(10,7) NOT NULL CHECK (latitude BETWEEN -90 AND 90),
  longitude numeric(10,7) NOT NULL CHECK (longitude BETWEEN -180 AND 180),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.races (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(180) NOT NULL,
  race_point_id bigint REFERENCES public.race_points(id) ON DELETE RESTRICT,
  release_location varchar(180) NOT NULL,
  release_latitude numeric(10,7) NOT NULL CHECK (release_latitude BETWEEN -90 AND 90),
  release_longitude numeric(10,7) NOT NULL CHECK (release_longitude BETWEEN -180 AND 180),
  release_at_utc timestamp without time zone,
  status varchar(10) NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','open','closed')),
  CONSTRAINT races_open_requires_release_time CHECK (status <> 'open' OR release_at_utc IS NOT NULL),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.race_entries (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  race_id bigint NOT NULL REFERENCES public.races(id),
  member_id bigint NOT NULL REFERENCES public.members(id),
  pigeon_ring varchar(80),
  barcode varchar(120) COLLATE "C",
  pooling smallint NOT NULL DEFAULT 0 CHECK (pooling IN (0,1)),
  category varchar(100) NOT NULL DEFAULT 'Open Category',
  race_type varchar(100) NOT NULL DEFAULT 'Regular Race/Set',
  distance_m numeric(13,3) NOT NULL CHECK (distance_m >= 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT unique_race_ring UNIQUE (race_id,pigeon_ring),
  CONSTRAINT unique_race_barcode UNIQUE (race_id,barcode)
);
CREATE TABLE IF NOT EXISTS public.clock_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  race_entry_id bigint NOT NULL REFERENCES public.race_entries(id),
  pigeon_ring varchar(80) NOT NULL,
  received_at_utc timestamp without time zone NOT NULL,
  source varchar(20) NOT NULL DEFAULT 'admin_manual' CHECK (source IN ('admin_manual','barcode')),
  verification varchar(20) NOT NULL DEFAULT 'provisional' CHECK (verification IN ('provisional','verified','rejected')),
  created_by_admin_id bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT unique_pigeon_clock UNIQUE (race_entry_id)
);
CREATE INDEX IF NOT EXISTS idx_race_point_location ON public.race_points(location);
CREATE INDEX IF NOT EXISTS idx_race_point_sector ON public.race_points(sector);
CREATE INDEX IF NOT EXISTS idx_race_status ON public.races(status);
CREATE INDEX IF NOT EXISTS idx_race_entries_race ON public.race_entries(race_id);
CREATE INDEX IF NOT EXISTS idx_race_entries_member ON public.race_entries(member_id);

CREATE TABLE IF NOT EXISTS public.app_profiles (
  id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  username text UNIQUE CHECK (username IS NULL OR username ~ '^[a-z0-9][a-z0-9_.-]{2,31}$'),
  role text NOT NULL CHECK (role IN ('admin','member')),
  member_id bigint UNIQUE REFERENCES public.members(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT app_profiles_member_role CHECK ((role='member' AND member_id IS NOT NULL) OR (role='admin' AND member_id IS NULL))
);

-- Add usernames safely when upgrading a project that already ran the prior schema.
ALTER TABLE public.app_profiles ADD COLUMN IF NOT EXISTS username text;
CREATE UNIQUE INDEX IF NOT EXISTS app_profiles_username_unique ON public.app_profiles (lower(username)) WHERE username IS NOT NULL;

CREATE OR REPLACE FUNCTION public.current_app_role()
RETURNS text LANGUAGE sql STABLE SECURITY DEFINER SET search_path = '' AS $$
  SELECT p.role FROM public.app_profiles p WHERE p.id = (SELECT auth.uid())
$$;
CREATE OR REPLACE FUNCTION public.current_member_id()
RETURNS bigint LANGUAGE sql STABLE SECURITY DEFINER SET search_path = '' AS $$
  SELECT p.member_id FROM public.app_profiles p
  WHERE p.id = (SELECT auth.uid()) AND p.role = 'member'
$$;
CREATE OR REPLACE FUNCTION public.is_app_admin()
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = '' AS $$
  SELECT COALESCE(public.current_app_role() = 'admin', false)
$$;
REVOKE ALL ON FUNCTION public.current_app_role() FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION public.current_member_id() FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION public.is_app_admin() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.current_app_role() TO authenticated;
GRANT EXECUTE ON FUNCTION public.current_member_id() TO authenticated;
GRANT EXECUTE ON FUNCTION public.is_app_admin() TO authenticated;

ALTER TABLE public.app_profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.members ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.race_points ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.races ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.race_entries ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.clock_events ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS profile_read_self_or_admin ON public.app_profiles;
CREATE POLICY profile_read_self_or_admin ON public.app_profiles
  FOR SELECT TO authenticated USING (id=(SELECT auth.uid()) OR public.is_app_admin());
DROP POLICY IF EXISTS members_read_authorized ON public.members;
CREATE POLICY members_read_authorized ON public.members
  FOR SELECT TO authenticated USING (public.is_app_admin() OR id=public.current_member_id());
DROP POLICY IF EXISTS members_admin_write ON public.members;
CREATE POLICY members_admin_write ON public.members
  FOR ALL TO authenticated USING (public.is_app_admin()) WITH CHECK (public.is_app_admin());
DROP POLICY IF EXISTS points_read_authenticated ON public.race_points;
CREATE POLICY points_read_authenticated ON public.race_points
  FOR SELECT TO authenticated USING (true);
DROP POLICY IF EXISTS points_admin_write ON public.race_points;
CREATE POLICY points_admin_write ON public.race_points
  FOR ALL TO authenticated USING (public.is_app_admin()) WITH CHECK (public.is_app_admin());
DROP POLICY IF EXISTS races_read_authenticated ON public.races;
CREATE POLICY races_read_authenticated ON public.races
  FOR SELECT TO authenticated USING (true);
DROP POLICY IF EXISTS races_admin_write ON public.races;
CREATE POLICY races_admin_write ON public.races
  FOR ALL TO authenticated USING (public.is_app_admin()) WITH CHECK (public.is_app_admin());
DROP POLICY IF EXISTS entries_read_authorized ON public.race_entries;
CREATE POLICY entries_read_authorized ON public.race_entries
  FOR SELECT TO authenticated USING (public.is_app_admin() OR member_id=public.current_member_id());
DROP POLICY IF EXISTS entries_admin_write ON public.race_entries;
CREATE POLICY entries_admin_write ON public.race_entries
  FOR ALL TO authenticated USING (public.is_app_admin()) WITH CHECK (public.is_app_admin());
DROP POLICY IF EXISTS clocks_read_authorized ON public.clock_events;
CREATE POLICY clocks_read_authorized ON public.clock_events
  FOR SELECT TO authenticated USING (
    public.is_app_admin() OR EXISTS (
      SELECT 1 FROM public.race_entries e
      WHERE e.id=clock_events.race_entry_id AND e.member_id=public.current_member_id()
    )
  );
DROP POLICY IF EXISTS clocks_admin_write ON public.clock_events;
CREATE POLICY clocks_admin_write ON public.clock_events
  FOR ALL TO authenticated USING (public.is_app_admin()) WITH CHECK (public.is_app_admin());

REVOKE ALL ON public.app_profiles, public.members, public.race_points, public.races,
  public.race_entries, public.clock_events FROM anon, PUBLIC;
DO $$
BEGIN
  IF to_regclass('public.admins') IS NOT NULL THEN
    EXECUTE 'ALTER TABLE public.admins ENABLE ROW LEVEL SECURITY';
    EXECUTE 'REVOKE ALL ON public.admins FROM anon, authenticated, PUBLIC';
  END IF;
  IF to_regclass('public.member_auth') IS NOT NULL THEN
    EXECUTE 'ALTER TABLE public.member_auth ENABLE ROW LEVEL SECURITY';
    EXECUTE 'REVOKE ALL ON public.member_auth FROM anon, authenticated, PUBLIC';
  END IF;
  IF to_regclass('public.sms_receipts') IS NOT NULL THEN
    EXECUTE 'ALTER TABLE public.sms_receipts ENABLE ROW LEVEL SECURITY';
    EXECUTE 'REVOKE ALL ON public.sms_receipts FROM anon, authenticated, PUBLIC';
  END IF;
END;
$$;
GRANT USAGE ON SCHEMA public TO authenticated;
GRANT SELECT ON public.app_profiles, public.members, public.race_points, public.races,
  public.race_entries, public.clock_events TO authenticated;
GRANT INSERT, UPDATE, DELETE ON public.members, public.race_points, public.races,
  public.race_entries, public.clock_events TO authenticated;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO authenticated;

CREATE OR REPLACE FUNCTION public.submit_member_clock(p_race_id bigint, p_barcode text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE
  v_member_id bigint;
  v_entry public.race_entries%ROWTYPE;
  v_race public.races%ROWTYPE;
  v_now timestamp without time zone;
  v_clock public.clock_events%ROWTYPE;
BEGIN
  v_member_id := public.current_member_id();
  IF v_member_id IS NULL THEN RAISE EXCEPTION 'Member account required.' USING ERRCODE='42501'; END IF;
  IF p_race_id IS NULL OR p_race_id < 1 OR p_barcode IS NULL OR length(p_barcode) NOT BETWEEN 1 AND 120 THEN
    RAISE EXCEPTION 'Enter a valid race and barcode.' USING ERRCODE='22023';
  END IF;
  SELECT e.* INTO v_entry FROM public.race_entries e
  WHERE e.race_id=p_race_id AND e.member_id=v_member_id AND e.barcode=p_barcode COLLATE "C"
  FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Barcode is not registered to your account for this race.' USING ERRCODE='22023'; END IF;
  SELECT r.* INTO v_race FROM public.races r WHERE r.id=p_race_id;
  IF v_race.status <> 'open' THEN RAISE EXCEPTION 'This race is not open for clocking.' USING ERRCODE='22023'; END IF;
  v_now := clock_timestamp() AT TIME ZONE 'UTC';
  IF v_now <= v_race.release_at_utc THEN RAISE EXCEPTION 'This race has not started yet.' USING ERRCODE='22023'; END IF;
  SELECT c.* INTO v_clock FROM public.clock_events c WHERE c.race_entry_id=v_entry.id;
  IF FOUND THEN
    RETURN jsonb_build_object('status','duplicate','message','This pigeon already has a receipt.','receipt_id',v_clock.id,'received_at_utc',v_clock.received_at_utc,'pigeon_ring',v_entry.pigeon_ring);
  END IF;
  INSERT INTO public.clock_events(race_entry_id,pigeon_ring,received_at_utc,source,verification)
    VALUES (v_entry.id,v_entry.pigeon_ring,v_now,'barcode','provisional') RETURNING * INTO v_clock;
  RETURN jsonb_build_object('status','accepted','message','Clocking received and marked provisional.','receipt_id',v_clock.id,'received_at_utc',v_clock.received_at_utc,'pigeon_ring',v_entry.pigeon_ring);
END;
$$;
REVOKE ALL ON FUNCTION public.submit_member_clock(bigint,text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.submit_member_clock(bigint,text) TO authenticated;

CREATE OR REPLACE FUNCTION public.admin_record_clock(p_entry_id bigint)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE
  v_entry public.race_entries%ROWTYPE;
  v_race public.races%ROWTYPE;
  v_now timestamp without time zone;
  v_clock public.clock_events%ROWTYPE;
BEGIN
  IF NOT public.is_app_admin() THEN RAISE EXCEPTION 'Administrator account required.' USING ERRCODE='42501'; END IF;
  SELECT e.* INTO v_entry FROM public.race_entries e WHERE e.id=p_entry_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Race entry not found.' USING ERRCODE='22023'; END IF;
  SELECT r.* INTO v_race FROM public.races r WHERE r.id=v_entry.race_id;
  IF v_race.status <> 'open' THEN RAISE EXCEPTION 'This race is not open for clocking.' USING ERRCODE='22023'; END IF;
  v_now := clock_timestamp() AT TIME ZONE 'UTC';
  IF v_now <= v_race.release_at_utc THEN RAISE EXCEPTION 'This race has not started yet.' USING ERRCODE='22023'; END IF;
  SELECT c.* INTO v_clock FROM public.clock_events c WHERE c.race_entry_id=v_entry.id;
  IF FOUND THEN RETURN jsonb_build_object('status','duplicate','message','This pigeon already has a receipt.','receipt_id',v_clock.id); END IF;
  INSERT INTO public.clock_events(race_entry_id,pigeon_ring,received_at_utc,source,verification,created_by_admin_id)
    VALUES (v_entry.id,v_entry.pigeon_ring,v_now,'admin_manual','provisional',NULL) RETURNING * INTO v_clock;
  RETURN jsonb_build_object('status','accepted','message','Clocking received and marked provisional.','receipt_id',v_clock.id,'received_at_utc',v_clock.received_at_utc);
END;
$$;
REVOKE ALL ON FUNCTION public.admin_record_clock(bigint) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.admin_record_clock(bigint) TO authenticated;
