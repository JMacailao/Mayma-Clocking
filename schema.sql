-- Fresh Supabase/PostgreSQL installation. Run as the database owner in SQL Editor.
-- This does not transfer data from an existing MySQL database.
BEGIN;
SET LOCAL TIME ZONE 'UTC';
SET LOCAL search_path TO public;

CREATE TABLE IF NOT EXISTS admins (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username VARCHAR(100) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS members (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 member_no VARCHAR(40) NOT NULL UNIQUE,
 full_name VARCHAR(180) NOT NULL,
 first_name VARCHAR(180) NULL,
 middle_name VARCHAR(180) NULL,
 last_name VARCHAR(180) NULL,
 loft_name VARCHAR(180) NOT NULL,
 address VARCHAR(500) NULL,
 phone VARCHAR(40) NULL,
 paid SMALLINT NOT NULL DEFAULT 0 CHECK (paid IN (0,1)),
 latitude DECIMAL(10,7) NOT NULL,
 longitude DECIMAL(10,7) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS race_points (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 location VARCHAR(180) NOT NULL,
 description VARCHAR(500) NULL,
 sector VARCHAR(100) NOT NULL,
 latitude DECIMAL(10,7) NOT NULL,
 longitude DECIMAL(10,7) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS races (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(180) NOT NULL,
 race_point_id BIGINT NULL,
 release_location VARCHAR(180) NOT NULL,
 release_latitude DECIMAL(10,7) NOT NULL,
 release_longitude DECIMAL(10,7) NOT NULL,
 release_at_utc TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
 status VARCHAR(10) CHECK (status IN ('draft','open','closed')) NOT NULL DEFAULT 'draft',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_race_point FOREIGN KEY (race_point_id) REFERENCES race_points(id) ON DELETE RESTRICT
);
CREATE TABLE IF NOT EXISTS race_entries (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 race_id BIGINT NOT NULL,
 member_id BIGINT NOT NULL,
 pigeon_ring VARCHAR(80) NULL,
 barcode VARCHAR(120) COLLATE "C" NULL,
 pooling SMALLINT NOT NULL DEFAULT 0 CHECK (pooling IN (0,1)),
 category VARCHAR(100) NOT NULL DEFAULT 'Open Category',
 race_type VARCHAR(100) NOT NULL DEFAULT 'Regular Race/Set',
 distance_m DECIMAL(13,3) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT unique_race_ring UNIQUE (race_id, pigeon_ring),
 CONSTRAINT unique_race_barcode UNIQUE (race_id, barcode),
 CONSTRAINT fk_entry_race FOREIGN KEY (race_id) REFERENCES races(id),
 CONSTRAINT fk_entry_member FOREIGN KEY (member_id) REFERENCES members(id)
);
CREATE TABLE IF NOT EXISTS clock_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 race_entry_id BIGINT NOT NULL,
 pigeon_ring VARCHAR(80) NOT NULL,
 received_at_utc TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
 source VARCHAR(20) CHECK (source IN ('admin_manual','barcode','sms')) NOT NULL DEFAULT 'admin_manual',
 verification VARCHAR(20) CHECK (verification IN ('provisional','verified','rejected')) NOT NULL DEFAULT 'provisional',
 created_by_admin_id BIGINT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT unique_pigeon_clock UNIQUE (race_entry_id),
 CONSTRAINT fk_clock_entry FOREIGN KEY (race_entry_id) REFERENCES race_entries(id),
 CONSTRAINT fk_clock_admin FOREIGN KEY (created_by_admin_id) REFERENCES admins(id)
);

CREATE TABLE IF NOT EXISTS member_auth (
 member_id BIGINT PRIMARY KEY,
 pin_hash VARCHAR(255) NOT NULL,
 issued_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_member_auth_member FOREIGN KEY (member_id) REFERENCES members(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS sms_receipts (
 provider_message_id VARCHAR(180) PRIMARY KEY,
 sender_phone VARCHAR(20) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_race_point_location ON race_points (location);
CREATE INDEX IF NOT EXISTS idx_race_point_sector ON race_points (sector);
CREATE INDEX IF NOT EXISTS idx_race_status ON races (status);
CREATE INDEX IF NOT EXISTS idx_race_entries_race ON race_entries (race_id);
CREATE INDEX IF NOT EXISTS idx_race_entries_member ON race_entries (member_id);

-- Keep update timestamps accurate, replacing MySQL's ON UPDATE behavior.
CREATE OR REPLACE FUNCTION public.pigeon_clock_touch_updated_at()
RETURNS trigger LANGUAGE plpgsql SET search_path = public AS $$
BEGIN
    NEW.updated_at = clock_timestamp() AT TIME ZONE 'UTC';
    RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS touch_updated_at ON public.members;
CREATE TRIGGER touch_updated_at BEFORE UPDATE ON public.members
FOR EACH ROW EXECUTE FUNCTION public.pigeon_clock_touch_updated_at();
DROP TRIGGER IF EXISTS touch_updated_at ON public.race_points;
CREATE TRIGGER touch_updated_at BEFORE UPDATE ON public.race_points
FOR EACH ROW EXECUTE FUNCTION public.pigeon_clock_touch_updated_at();
DROP TRIGGER IF EXISTS touch_updated_at ON public.race_entries;
CREATE TRIGGER touch_updated_at BEFORE UPDATE ON public.race_entries
FOR EACH ROW EXECUTE FUNCTION public.pigeon_clock_touch_updated_at();

-- Authentication remains in PHP. These tables must not be exposed through
-- Supabase's browser-facing Data API. No anon/authenticated policies are added.
ALTER TABLE public.admins ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.members ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.race_points ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.races ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.race_entries ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.clock_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.member_auth ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sms_receipts ENABLE ROW LEVEL SECURITY;
DO $$
DECLARE role_name text;
BEGIN
    FOREACH role_name IN ARRAY ARRAY['anon', 'authenticated'] LOOP
        IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = role_name) THEN
            EXECUTE format('REVOKE ALL ON TABLE public.admins, public.members, public.race_points, public.races, public.race_entries, public.clock_events, public.member_auth, public.sms_receipts FROM %I', role_name);
        END IF;
    END LOOP;
END;
$$;
COMMIT;
