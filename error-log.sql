-- AvilonX Clocking: errors from people's browsers and the Android app.
--
-- When a page breaks, the website sends a short report here (message, page,
-- browser; never form contents). The same error within 10 minutes only adds to
-- its count. The Super Admin reads them on Club accounts → App errors. At most
-- 300 reports an hour are kept, and reports older than 30 days are removed.
--
-- Run after multi-club.sql. Safe to run again.

CREATE TABLE IF NOT EXISTS public.client_errors (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  message text NOT NULL CHECK (length(message) <= 500),
  source text NOT NULL DEFAULT '' CHECK (length(source) <= 300),
  page text NOT NULL DEFAULT '' CHECK (length(page) <= 200),
  user_agent text NOT NULL DEFAULT '' CHECK (length(user_agent) <= 300),
  app_version text NOT NULL DEFAULT '' CHECK (length(app_version) <= 40),
  user_id uuid,
  club_id bigint,
  count integer NOT NULL DEFAULT 1,
  first_at timestamptz NOT NULL DEFAULT now(),
  last_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_client_errors_last ON public.client_errors(last_at DESC);
ALTER TABLE public.client_errors ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.client_errors FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.log_client_error(p_message text, p_source text DEFAULT '', p_page text DEFAULT '', p_user_agent text DEFAULT '', p_app_version text DEFAULT '')
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_message text := left(btrim(coalesce(p_message, '')), 500); v_page text := left(coalesce(p_page, ''), 200); v_id bigint;
BEGIN
  IF v_message = '' THEN RETURN; END IF;
  SELECT id INTO v_id FROM public.client_errors
   WHERE message = v_message AND page = v_page AND last_at > now() - interval '10 minutes' ORDER BY id DESC LIMIT 1;
  IF v_id IS NOT NULL THEN
    UPDATE public.client_errors SET count = count + 1, last_at = now() WHERE id = v_id;
    RETURN;
  END IF;
  IF (SELECT count(*) FROM public.client_errors WHERE first_at > now() - interval '1 hour') >= 300 THEN RETURN; END IF;
  INSERT INTO public.client_errors (message, source, page, user_agent, app_version, user_id, club_id)
  VALUES (v_message, left(coalesce(p_source, ''), 300), v_page, left(coalesce(p_user_agent, ''), 300), left(coalesce(p_app_version, ''), 40),
    (SELECT auth.uid()), (SELECT p.club_id FROM public.app_profiles AS p WHERE p.id = (SELECT auth.uid())));
  DELETE FROM public.client_errors WHERE last_at < now() - interval '30 days';
END;
$$;
REVOKE ALL ON FUNCTION public.log_client_error(text, text, text, text, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.log_client_error(text, text, text, text, text) TO anon, authenticated;

CREATE OR REPLACE FUNCTION public.superadmin_client_errors()
RETURNS TABLE (id bigint, message text, source text, page text, user_agent text, app_version text, username text, club_name text, count integer, first_at timestamptz, last_at timestamptz)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = '' AS $$
BEGIN
  IF NOT public.is_superadmin() THEN RAISE EXCEPTION 'Super Admin only.' USING ERRCODE = '42501'; END IF;
  RETURN QUERY SELECT e.id, e.message, e.source, e.page, e.user_agent, e.app_version, p.username::text, c.name::text, e.count, e.first_at, e.last_at
    FROM public.client_errors AS e LEFT JOIN public.app_profiles AS p ON p.id = e.user_id LEFT JOIN public.clubs AS c ON c.id = e.club_id
    ORDER BY e.last_at DESC LIMIT 100;
END;
$$;
CREATE OR REPLACE FUNCTION public.superadmin_clear_client_errors()
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
BEGIN
  IF NOT public.is_superadmin() THEN RAISE EXCEPTION 'Super Admin only.' USING ERRCODE = '42501'; END IF;
  DELETE FROM public.client_errors WHERE true;
END;
$$;
REVOKE ALL ON FUNCTION public.superadmin_client_errors(), public.superadmin_clear_client_errors() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.superadmin_client_errors(), public.superadmin_clear_client_errors() TO authenticated;

