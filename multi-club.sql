-- Only an empty club can be deleted; this removes its account too.
CREATE OR REPLACE FUNCTION public.superadmin_delete_club(p_club_id bigint)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
BEGIN
  IF NOT public.is_superadmin() THEN RAISE EXCEPTION 'Superadmin account required.' USING ERRCODE='42501'; END IF;
  IF EXISTS (SELECT 1 FROM public.members WHERE club_id=p_club_id)
     OR EXISTS (SELECT 1 FROM public.races WHERE club_id=p_club_id)
     OR EXISTS (SELECT 1 FROM public.race_points WHERE club_id=p_club_id) THEN
    RAISE EXCEPTION 'This club still has members, races or race points. The club must delete them first.' USING ERRCODE='23503';
  END IF;
  DELETE FROM auth.users WHERE id IN (SELECT p.id FROM public.app_profiles p WHERE p.club_id=p_club_id);
  DELETE FROM public.clubs WHERE id=p_club_id;
  RETURN jsonb_build_object('status','deleted');
END;
$$;
REVOKE ALL ON FUNCTION public.superadmin_delete_club(bigint) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.superadmin_delete_club(bigint) TO authenticated;

