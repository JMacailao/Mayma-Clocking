ALTER TABLE public.races        ADD COLUMN IF NOT EXISTS club_id bigint REFERENCES public.clubs(id);

-- Data created before clubs existed is kept under a club named "Default club".
-- Create a club account with exactly that name to take it over.
DO $$
DECLARE v_club bigint;
BEGIN
  IF EXISTS (SELECT 1 FROM public.members WHERE club_id IS NULL)
     OR EXISTS (SELECT 1 FROM public.race_points WHERE club_id IS NULL)
     OR EXISTS (SELECT 1 FROM public.races WHERE club_id IS NULL) THEN
    SELECT id INTO v_club FROM public.clubs WHERE lower(name)='default club';
    IF v_club IS NULL THEN INSERT INTO public.clubs(name) VALUES ('Default club') RETURNING id INTO v_club; END IF;
    UPDATE public.members     SET club_id=v_club WHERE club_id IS NULL;
    UPDATE public.race_points SET club_id=v_club WHERE club_id IS NULL;
    UPDATE public.races       SET club_id=v_club WHERE club_id IS NULL;
  END IF;
END $$;

UPDATE public.app_profiles p SET club_id=m.club_id
  FROM public.members m WHERE p.member_id=m.id AND p.role='member' AND p.club_id IS NULL;
-- The account that was the single administrator becomes the superadmin.
UPDATE public.app_profiles SET role='superadmin' WHERE role='admin' AND club_id IS NULL;

ALTER TABLE public.app_profiles ADD CONSTRAINT app_profiles_role_shape CHECK (
  (role='superadmin' AND member_id IS NULL AND club_id IS NULL) OR
  (role='admin'      AND member_id IS NULL AND club_id IS NOT NULL) OR
  (role='staff'      AND member_id IS NULL AND club_id IS NOT NULL) OR
  (role='member'     AND member_id IS NOT NULL AND club_id IS NOT NULL));

