CREATE OR REPLACE FUNCTION public.superadmin_set_club_password(p_club_id bigint, p_password text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_user uuid;
BEGIN
  IF NOT public.is_superadmin() THEN RAISE EXCEPTION 'Superadmin account required.' USING ERRCODE='42501'; END IF;
  IF p_password IS NULL OR length(p_password) < 8 THEN
    RAISE EXCEPTION 'Password must be at least 8 characters.' USING ERRCODE='22023';
