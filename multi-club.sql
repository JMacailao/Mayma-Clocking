CREATE OR REPLACE FUNCTION public.superadmin_create_club(p_club_name text, p_username text, p_password text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_name text := trim(p_club_name); v_username text := lower(trim(p_username)); v_club bigint; v_id uuid;
BEGIN
  IF NOT public.is_superadmin() THEN RAISE EXCEPTION 'Superadmin account required.' USING ERRCODE='42501'; END IF;
  IF v_name IS NULL OR length(v_name) NOT BETWEEN 2 AND 180 THEN
    RAISE EXCEPTION 'Club name must be 2–180 characters.' USING ERRCODE='22023';
  END IF;
  SELECT c.id INTO v_club FROM public.clubs c WHERE lower(c.name)=lower(v_name);
  IF v_club IS NOT NULL THEN
    IF EXISTS (SELECT 1 FROM public.app_profiles p WHERE p.club_id=v_club AND p.role='admin') THEN
      RAISE EXCEPTION 'A club with this name already has an account.' USING ERRCODE='23505';
    END IF;
  ELSE
    INSERT INTO public.clubs(name) VALUES (v_name) RETURNING id INTO v_club;
  END IF;
  v_id := public._create_auth_user(v_username, p_password);
  INSERT INTO public.app_profiles(id, username, role, member_id, club_id) VALUES (v_id, v_username, 'admin', NULL, v_club);
  RETURN jsonb_build_object('status','created','club_id',v_club,'username',v_username);
END;
$$;
REVOKE ALL ON FUNCTION public.superadmin_create_club(text,text,text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.superadmin_create_club(text,text,text) TO authenticated;

CREATE OR REPLACE FUNCTION public.superadmin_list_clubs()
RETURNS TABLE(id bigint, name text, admin_username text, member_count bigint, race_count bigint, created_at timestamptz)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = '' AS $$
  SELECT c.id, c.name::text,
         (SELECT p.username FROM public.app_profiles p WHERE p.club_id=c.id AND p.role='admin' LIMIT 1),
         (SELECT count(*) FROM public.members m WHERE m.club_id=c.id),
         (SELECT count(*) FROM public.races r WHERE r.club_id=c.id),
         c.created_at
  FROM public.clubs c
  WHERE public.is_superadmin()
  ORDER BY c.id DESC
$$;
