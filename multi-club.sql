-- Mayma Clocking: multi-club. Run AFTER supabase-auth.sql. Safe to re-run.
--   superadmin  : created on first run; manages club accounts and global stickers.
--   admin       : manages its own club, including team accounts.
--   staff        : manages routine club records, but not accounts.
--   member      : belongs to a club; sees only their own records.
-- Every club-owned table carries club_id, and row-level security enforces it.
BEGIN;

DO $$
BEGIN
  IF to_regclass('public.app_profiles') IS NULL OR to_regprocedure('public._create_auth_user(text,text)') IS NULL THEN
    RAISE EXCEPTION 'Run schema.sql (fresh database) and supabase-auth.sql first.';
  END IF;
  IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public'
             AND table_name='app_profiles' AND column_name='id' AND data_type='text') THEN
    RAISE EXCEPTION 'Run supabase-auth.sql first; it removes the Firebase version.';
  END IF;
END $$;

-- 1. Policies off while structures change -------------------------------------------------
DO $$
DECLARE r record;
BEGIN
  FOR r IN SELECT schemaname, tablename, policyname FROM pg_policies
           WHERE schemaname='public' AND tablename IN
           ('app_profiles','members','race_points','races','race_entries','clock_events','clubs')
  LOOP
    EXECUTE format('DROP POLICY IF EXISTS %I ON %I.%I', r.policyname, r.schemaname, r.tablename);
  END LOOP;
  FOR r IN SELECT conname FROM pg_constraint
           WHERE conrelid='public.app_profiles'::regclass AND contype='c'
             AND pg_get_constraintdef(oid) ILIKE '%role%'
  LOOP
    EXECUTE format('ALTER TABLE public.app_profiles DROP CONSTRAINT %I', r.conname);
  END LOOP;
END $$;

