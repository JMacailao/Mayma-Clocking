-- AvilonX Clocking: race entry remarks.
--
-- The club administrator builds the club's list of remarks (for example
-- "Vaccinated", "Fee paid", "Late entry"). On Race entries each remark is a
-- tick box: the person registering a pigeon ticks as many as apply, and the
-- ticked remarks are saved with the entry.
--
-- Run after multi-club.sql. Safe to run again.

CREATE TABLE IF NOT EXISTS public.entry_remark_options (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  club_id bigint NOT NULL DEFAULT public.current_club_id() REFERENCES public.clubs(id) ON DELETE CASCADE,
  label text NOT NULL CHECK (length(btrim(label)) BETWEEN 1 AND 60),
  sort_order integer NOT NULL DEFAULT 0,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS entry_remark_options_club_label_key
  ON public.entry_remark_options (club_id, lower(btrim(label)));

ALTER TABLE public.entry_remark_options ENABLE ROW LEVEL SECURITY;
-- Admins and staff see the club's remarks (staff register entries too); only
-- the club administrator changes the list.
DROP POLICY IF EXISTS entry_remark_options_read ON public.entry_remark_options;
CREATE POLICY entry_remark_options_read ON public.entry_remark_options
  FOR SELECT TO authenticated
  USING (public.can_manage_club_data() AND club_id = public.current_club_id());
DROP POLICY IF EXISTS entry_remark_options_admin_write ON public.entry_remark_options;
CREATE POLICY entry_remark_options_admin_write ON public.entry_remark_options
  FOR ALL TO authenticated
  USING (public.is_app_admin() AND club_id = public.current_club_id())
  WITH CHECK (public.is_app_admin() AND club_id = public.current_club_id());
GRANT SELECT, INSERT, UPDATE, DELETE ON public.entry_remark_options TO authenticated;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO authenticated;

-- The remarks ticked for each entry, stored as their text so an entry keeps
-- its remarks even if the admin later renames or deletes one.
ALTER TABLE public.race_entries ADD COLUMN IF NOT EXISTS remarks text[] NOT NULL DEFAULT '{}';
ALTER TABLE public.race_entries DROP CONSTRAINT IF EXISTS race_entries_remarks_limit;
ALTER TABLE public.race_entries ADD CONSTRAINT race_entries_remarks_limit CHECK (cardinality(remarks) <= 30);

-- Practice races (Race schedules → "Practice race") never appear in the
-- public results.
ALTER TABLE public.races ADD COLUMN IF NOT EXISTS is_practice boolean NOT NULL DEFAULT false;

-- Public results show each ring with its remarks, e.g. "12345 P1/P2/P3".
-- Each row also has its rank in its race (by speed), the race's status (open
-- = results can still change, closed = final), its Show up verification
-- (verified or provisional) and whether it is disqualified (DQ: the race is
-- closed and the bird never showed up). DQ birds are listed, not ranked, after
-- the ranked ones. Clocks the club rejected are left out. This replaces the version in public-results.sql;
-- run this file again after re-running public-results.sql.
DROP FUNCTION IF EXISTS public.public_race_results(bigint, date);
CREATE FUNCTION public.public_race_results(p_club_id bigint, p_race_date date)
RETURNS TABLE(
  race_name text,
  loft_name text,
  distance_m numeric,
  pigeon_ring text,
  barcode text,
  arrival_at_utc timestamp without time zone,
  flight_seconds numeric,
  speed_m_per_min numeric,
  rank bigint,
  race_status text,
  verification text,
  disqualified boolean
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $function$
  SELECT
    x.race_name, x.loft_name, x.distance_m, x.pigeon_ring, x.barcode, x.arrival_at_utc, x.flight_seconds, x.speed_m_per_min,
    CASE WHEN x.speed_m_per_min IS NOT NULL AND NOT x.disqualified
      THEN rank() OVER (PARTITION BY x.race_id, x.disqualified ORDER BY x.speed_m_per_min DESC NULLS LAST) END,
    x.race_status, x.verification, x.disqualified
  FROM (
    SELECT
      r.id AS race_id,
      r.name::text AS race_name,
      m.loft_name::text AS loft_name,
      e.distance_m::numeric AS distance_m,
      (COALESCE(e.pigeon_ring, c.pigeon_ring)
        || CASE WHEN cardinality(e.remarks) > 0 THEN ' ' || array_to_string(e.remarks, '/') ELSE '' END)::text AS pigeon_ring,
      COALESCE(e.barcode, '')::text AS barcode,
      c.received_at_utc AS arrival_at_utc,
      CASE
        WHEN c.received_at_utc > r.release_at_utc
          THEN EXTRACT(EPOCH FROM (c.received_at_utc - r.release_at_utc))
        ELSE NULL::numeric
      END AS flight_seconds,
      CASE
        WHEN c.received_at_utc > r.release_at_utc
          THEN e.distance_m * 60 / NULLIF(EXTRACT(EPOCH FROM (c.received_at_utc - r.release_at_utc)), 0)
        ELSE NULL::numeric
      END AS speed_m_per_min,
      r.status::text AS race_status,
      c.verification::text AS verification,
      -- Disqualified: the race is closed and the pigeon never showed up (Show up).
      (c.verification = 'provisional' AND r.status = 'closed') AS disqualified
    FROM public.clubs AS club
    JOIN public.races AS r ON r.club_id = club.id
    JOIN public.race_entries AS e ON e.race_id = r.id
    JOIN public.members AS m ON m.id = e.member_id AND m.club_id = club.id
    JOIN public.clock_events AS c ON c.race_entry_id = e.id
    WHERE club.id = p_club_id
      AND ((r.release_at_utc AT TIME ZONE 'UTC') AT TIME ZONE 'Asia/Manila')::date = p_race_date
      AND c.verification <> 'rejected'
      AND NOT r.is_practice
  ) AS x
  ORDER BY x.race_name, x.disqualified, x.speed_m_per_min DESC NULLS LAST, x.loft_name, x.pigeon_ring;
$function$;
REVOKE ALL ON FUNCTION public.public_race_results(bigint, date) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.public_race_results(bigint, date) TO anon, authenticated;
COMMENT ON FUNCTION public.public_race_results(bigint, date) IS
  'Public race results for a club and Philippines-local race date: rank, race status, Show up verification and DQ; no member or account data.';


-- Header of each race on the public results: release point (name and
-- coordinates), release time, status, and how many birds are entered and
-- clocked (clocks the club rejected are not counted), e.g. 9/10. No member data.
CREATE OR REPLACE FUNCTION public.public_race_summaries(p_club_id bigint, p_race_date date)
RETURNS TABLE(
  race_name text,
  release_location text,
  release_latitude numeric,
  release_longitude numeric,
  release_at_utc timestamp without time zone,
  race_status text,
  birds_entered bigint,
  birds_clocked bigint
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $function$
  SELECT
    r.name::text,
    r.release_location::text,
    r.release_latitude::numeric,
    r.release_longitude::numeric,
    r.release_at_utc,
    r.status::text,
    (SELECT count(*) FROM public.race_entries AS e WHERE e.race_id = r.id),
    (SELECT count(DISTINCT e.id) FROM public.race_entries AS e
       JOIN public.clock_events AS c ON c.race_entry_id = e.id
      WHERE e.race_id = r.id AND c.verification <> 'rejected')
  FROM public.races AS r
  WHERE r.club_id = p_club_id
    AND ((r.release_at_utc AT TIME ZONE 'UTC') AT TIME ZONE 'Asia/Manila')::date = p_race_date
    AND NOT r.is_practice
  ORDER BY r.name;
$function$;
REVOKE ALL ON FUNCTION public.public_race_summaries(bigint, date) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.public_race_summaries(bigint, date) TO anon, authenticated;
COMMENT ON FUNCTION public.public_race_summaries(bigint, date) IS
  'Public race headers for a club and Philippines-local race date: release point, coordinates, release time, status, birds clocked / entered; no member data.';

