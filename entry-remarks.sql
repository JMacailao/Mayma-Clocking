-- AvilonX Clocking: race entry remarks.
--
-- The club administrator builds the club's list of remarks (for example
-- "Vaccinated", "Fee paid", "Late entry"). On Race entries each remark is a
-- tick box: the person registering a pigeon ticks as many as apply, and the
-- ticked remarks are saved with the entry.
--
-- Run after multi-club.sql. Safe to run again.

CREATE TABLE IF NOT EXISTS public.entry_remark_options (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  club_id bigint NOT NULL DEFAULT public.current_club_id() REFERENCES public.clubs(id) ON DELETE CASCADE,
  label text NOT NULL CHECK (length(btrim(label)) BETWEEN 1 AND 60),
  sort_order integer NOT NULL DEFAULT 0,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS entry_remark_options_club_label_key
  ON public.entry_remark_options (club_id, lower(btrim(label)));

ALTER TABLE public.entry_remark_options ENABLE ROW LEVEL SECURITY;
-- Admins and staff see the club's remarks (staff register entries too); only
-- the club administrator changes the list.
DROP POLICY IF EXISTS entry_remark_options_read ON public.entry_remark_options;
CREATE POLICY entry_remark_options_read ON public.entry_remark_options
  FOR SELECT TO authenticated
  USING (public.can_manage_club_data() AND club_id = public.current_club_id());
DROP POLICY IF EXISTS entry_remark_options_admin_write ON public.entry_remark_options;
CREATE POLICY entry_remark_options_admin_write ON public.entry_remark_options
  FOR ALL TO authenticated
  USING (public.is_app_admin() AND club_id = public.current_club_id())
  WITH CHECK (public.is_app_admin() AND club_id = public.current_club_id());
GRANT SELECT, INSERT, UPDATE, DELETE ON public.entry_remark_options TO authenticated;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO authenticated;

-- The remarks ticked for each entry, stored as their text so an entry keeps
-- its remarks even if the admin later renames or deletes one.
ALTER TABLE public.race_entries ADD COLUMN IF NOT EXISTS remarks text[] NOT NULL DEFAULT '{}';
ALTER TABLE public.race_entries DROP CONSTRAINT IF EXISTS race_entries_remarks_limit;
ALTER TABLE public.race_entries ADD CONSTRAINT race_entries_remarks_limit CHECK (cardinality(remarks) <= 30);

-- Practice races (Race schedules → "Practice race") never appear in the
-- public results.
ALTER TABLE public.races ADD COLUMN IF NOT EXISTS is_practice boolean NOT NULL DEFAULT false;

-- Public results show each ring with its remarks, e.g. "12345 P1/P2/P3", and
-- leave out disqualified results (race closed, never verified on Show up).
-- This replaces the version in public-results.sql (same name and columns), so
-- run this file again after re-running public-results.sql.
CREATE OR REPLACE FUNCTION public.public_race_results(p_club_id bigint, p_race_date date)
RETURNS TABLE(
  race_name text,
  loft_name text,
  distance_m numeric,
  pigeon_ring text,
  barcode text,
  arrival_at_utc timestamp without time zone,
  flight_seconds numeric,
  speed_m_per_min numeric
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $function$
  SELECT
    r.name::text,
    m.loft_name::text,
    e.distance_m::numeric,
    (COALESCE(e.pigeon_ring, c.pigeon_ring)
      || CASE WHEN cardinality(e.remarks) > 0 THEN ' ' || array_to_string(e.remarks, '/') ELSE '' END)::text,
    COALESCE(e.barcode, '')::text,
    c.received_at_utc,
    CASE
      WHEN c.received_at_utc > r.release_at_utc
        THEN EXTRACT(EPOCH FROM (c.received_at_utc - r.release_at_utc))
      ELSE NULL::numeric
    END,
    CASE
      WHEN c.received_at_utc > r.release_at_utc
        THEN e.distance_m * 60 / NULLIF(EXTRACT(EPOCH FROM (c.received_at_utc - r.release_at_utc)), 0)
      ELSE NULL::numeric
    END
  FROM public.clubs AS club
  JOIN public.races AS r ON r.club_id = club.id
  JOIN public.race_entries AS e ON e.race_id = r.id
  JOIN public.members AS m ON m.id = e.member_id AND m.club_id = club.id
  JOIN public.clock_events AS c ON c.race_entry_id = e.id
  WHERE club.id = p_club_id
    AND ((r.release_at_utc AT TIME ZONE 'UTC') AT TIME ZONE 'Asia/Manila')::date = p_race_date
    AND c.verification <> 'rejected'
    -- Disqualified: the race is closed and the pigeon never showed up (Show up).
    AND NOT (c.verification = 'provisional' AND r.status = 'closed')
    AND NOT r.is_practice
  ORDER BY r.name, m.loft_name, e.pigeon_ring;
$function$;

