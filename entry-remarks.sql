-- AvilonX Clocking: race entry remarks.
--
-- The club administrator builds the club's list of remarks (for example
-- "Vaccinated", "Fee paid", "Late entry"). On Race entries each remark is a
-- tick box: the person registering a pigeon ticks as many as apply, and the
-- ticked remarks are saved with the entry.
--
-- Run after multi-club.sql. Safe to run again.

CREATE TABLE IF NOT EXISTS public.entry_remark_options (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  club_id bigint NOT NULL DEFAULT public.current_club_id() REFERENCES public.clubs(id) ON DELETE CASCADE,
  label text NOT NULL CHECK (length(btrim(label)) BETWEEN 1 AND 60),
  sort_order integer NOT NULL DEFAULT 0,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS entry_remark_options_club_label_key
  ON public.entry_remark_options (club_id, lower(btrim(label)));

ALTER TABLE public.entry_remark_options ENABLE ROW LEVEL SECURITY;
-- Admins and staff see the club's remarks (staff register entries too); only
-- the club administrator changes the list.
DROP POLICY IF EXISTS entry_remark_options_read ON public.entry_remark_options;
CREATE POLICY entry_remark_options_read ON public.entry_remark_options
  FOR SELECT TO authenticated
  USING (public.can_manage_club_data() AND club_id = public.current_club_id());
DROP POLICY IF EXISTS entry_remark_options_admin_write ON public.entry_remark_options;
CREATE POLICY entry_remark_options_admin_write ON public.entry_remark_options
  FOR ALL TO authenticated
  USING (public.is_app_admin() AND club_id = public.current_club_id())
  WITH CHECK (public.is_app_admin() AND club_id = public.current_club_id());
GRANT SELECT, INSERT, UPDATE, DELETE ON public.entry_remark_options TO authenticated;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO authenticated;

-- The remarks ticked for each entry, stored as their text so an entry keeps
-- its remarks even if the admin later renames or deletes one.
ALTER TABLE public.race_entries ADD COLUMN IF NOT EXISTS remarks text[] NOT NULL DEFAULT '{}';
ALTER TABLE public.race_entries DROP CONSTRAINT IF EXISTS race_entries_remarks_limit;
ALTER TABLE public.race_entries ADD CONSTRAINT race_entries_remarks_limit CHECK (cardinality(remarks) <= 30);

NOTIFY pgrst, 'reload schema';
