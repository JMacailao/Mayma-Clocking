-- AvilonX Clocking: a short video of each clocking.
--
-- After clocking, a member can add a short video (up to 30 seconds, 50 MB) of
-- the pigeon arriving. It is kept in a private Supabase Storage bucket,
-- "clock-videos", in a folder per club and member:
--   <club id>/<member id>/<clock id>/<time>.<ext>
-- The member sees their own videos; the club's administrators and staff see
-- every video of their club (Show up). One video per clock: a new one replaces
-- the old one.
--
-- Run after show-up.sql and before race-day.sql. Safe to run again.

CREATE TABLE IF NOT EXISTS public.clock_videos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clock_event_id bigint NOT NULL UNIQUE REFERENCES public.clock_events(id) ON DELETE CASCADE,
  member_id bigint NOT NULL REFERENCES public.members(id) ON DELETE CASCADE,
  club_id bigint NOT NULL,
  storage_path text NOT NULL,
  duration_seconds numeric(6,2),
  size_bytes bigint,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_clock_videos_club ON public.clock_videos(club_id);
CREATE INDEX IF NOT EXISTS idx_clock_videos_member ON public.clock_videos(member_id);

ALTER TABLE public.clock_videos ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS clock_videos_read ON public.clock_videos;
CREATE POLICY clock_videos_read ON public.clock_videos FOR SELECT TO authenticated
  USING ((public.can_manage_club_data() AND club_id = public.current_club_id()) OR member_id = public.current_member_id());
-- Saved only through member_save_clock_video(), which checks the clock is the member's.
REVOKE ALL ON public.clock_videos FROM anon, authenticated;
GRANT SELECT ON public.clock_videos TO authenticated;

-- Saves the video a member uploaded for one of their clocks. Returns the path of
-- the video it replaces (or null), so the website can delete that file.
CREATE OR REPLACE FUNCTION public.member_save_clock_video(p_clock_id bigint, p_path text, p_duration numeric, p_size bigint)
RETURNS jsonb LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path = '' AS $$
DECLARE
  v_member_id bigint := public.current_member_id();
  v_club_id bigint;
  v_old text;
  v_found boolean;
BEGIN
  IF v_member_id IS NULL THEN RAISE EXCEPTION 'Member account required.' USING ERRCODE = '42501'; END IF;
  SELECT r.club_id INTO v_club_id
  FROM public.clock_events AS c
  JOIN public.race_entries AS e ON e.id = c.race_entry_id
  JOIN public.races AS r ON r.id = e.race_id
  WHERE c.id = p_clock_id AND e.member_id = v_member_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'This clocking is not one of your pigeons.' USING ERRCODE = '42501'; END IF;
  IF p_path IS NULL OR p_path NOT LIKE v_club_id || '/' || v_member_id || '/' || p_clock_id || '/%' OR position('..' IN p_path) > 0 THEN
    RAISE EXCEPTION 'The video was not saved in your folder. Try again.' USING ERRCODE = '22023';
  END IF;
  IF p_duration IS NULL OR p_duration <= 0 OR p_duration > 31 THEN
    RAISE EXCEPTION 'The video must be 30 seconds or shorter.' USING ERRCODE = '22023';
  END IF;
  IF p_size IS NULL OR p_size <= 0 OR p_size > 52428800 THEN
    RAISE EXCEPTION 'The video must be 50 MB or smaller.' USING ERRCODE = '22023';
  END IF;
  IF to_regclass('storage.objects') IS NOT NULL THEN
    EXECUTE 'SELECT EXISTS (SELECT 1 FROM storage.objects WHERE bucket_id = $1 AND name = $2)' INTO v_found USING 'clock-videos', p_path;
    IF NOT v_found THEN RAISE EXCEPTION 'The video upload did not finish. Try again.' USING ERRCODE = '22023'; END IF;
  END IF;

  SELECT v.storage_path INTO v_old FROM public.clock_videos AS v WHERE v.clock_event_id = p_clock_id;
  INSERT INTO public.clock_videos (clock_event_id, member_id, club_id, storage_path, duration_seconds, size_bytes)
  VALUES (p_clock_id, v_member_id, v_club_id, p_path, round(p_duration, 2), p_size)
  ON CONFLICT (clock_event_id) DO UPDATE
    SET storage_path = EXCLUDED.storage_path, duration_seconds = EXCLUDED.duration_seconds,
        size_bytes = EXCLUDED.size_bytes, created_at = now();
  RETURN jsonb_build_object('status', 'saved', 'replaced_path', CASE WHEN v_old IS DISTINCT FROM p_path THEN v_old END);
END;
$$;
REVOKE ALL ON FUNCTION public.member_save_clock_video(bigint, text, numeric, bigint) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.member_save_clock_video(bigint, text, numeric, bigint) TO authenticated;

-- Private video bucket and who may use it (skipped where Supabase Storage is not installed).
DO $$
BEGIN
  IF to_regclass('storage.buckets') IS NULL OR to_regclass('storage.objects') IS NULL THEN
    RAISE NOTICE 'Supabase Storage not found: skipping the clock-videos bucket.';
    RETURN;
  END IF;
  INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
  VALUES ('clock-videos', 'clock-videos', false, 52428800,
          ARRAY['video/mp4', 'video/quicktime', 'video/webm', 'video/3gpp', 'video/x-matroska'])
  ON CONFLICT (id) DO UPDATE SET public = false, file_size_limit = EXCLUDED.file_size_limit, allowed_mime_types = EXCLUDED.allowed_mime_types;

  -- Read: the member's own folder, or any folder of the club for its administrators and staff.
  EXECUTE 'DROP POLICY IF EXISTS clock_videos_read ON storage.objects';
  EXECUTE $p$CREATE POLICY clock_videos_read ON storage.objects FOR SELECT TO authenticated USING (
    bucket_id = 'clock-videos' AND (
      (public.can_manage_club_data() AND (storage.foldername(name))[1] = public.current_club_id()::text)
      OR ((storage.foldername(name))[2] = public.current_member_id()::text
          AND (storage.foldername(name))[1] = public.current_club_id()::text)))$p$;
  -- Upload and delete: members, in their own folder only.
  EXECUTE 'DROP POLICY IF EXISTS clock_videos_member_insert ON storage.objects';
  EXECUTE $p$CREATE POLICY clock_videos_member_insert ON storage.objects FOR INSERT TO authenticated WITH CHECK (
    bucket_id = 'clock-videos' AND public.current_member_id() IS NOT NULL
    AND (storage.foldername(name))[1] = public.current_club_id()::text
    AND (storage.foldername(name))[2] = public.current_member_id()::text)$p$;
  EXECUTE 'DROP POLICY IF EXISTS clock_videos_member_delete ON storage.objects';
  EXECUTE $p$CREATE POLICY clock_videos_member_delete ON storage.objects FOR DELETE TO authenticated USING (
    bucket_id = 'clock-videos' AND public.current_member_id() IS NOT NULL
    AND (storage.foldername(name))[1] = public.current_club_id()::text
    AND (storage.foldername(name))[2] = public.current_member_id()::text)$p$;
END;
$$;

