-- AvilonX Clocking: bird bonding.
--
-- Before a pigeon can be entered in a race, the club administrator (or staff)
-- bonds it: ring number, bird name, colour, loft name, its RFID tag and a
-- photo. Race entries then choose one of the member's bonded birds; the ring
-- number and RFID tag are copied from the bond.
--
-- Photos are kept in a private Supabase Storage bucket, "pigeon-photos", in a
-- folder per club. Club admins/staff see their club's photos; a member sees
-- the photos of their own birds.
--
-- Run after nfc-tags.sql and sticker-barcodes.sql. Safe to run again.

DO $$
BEGIN
  IF to_regprocedure('public.normalize_nfc_uid(text)') IS NULL THEN
    RAISE EXCEPTION 'Run nfc-tags.sql before bird-bonding.sql.';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'race_entries' AND column_name = 'nfc_read_with') THEN
    RAISE EXCEPTION 'Run the latest nfc-tags.sql first, then bird-bonding.sql.';
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS public.pigeons (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  club_id bigint NOT NULL DEFAULT public.current_club_id() REFERENCES public.clubs(id) ON DELETE CASCADE,
  member_id bigint NOT NULL REFERENCES public.members(id) ON DELETE CASCADE,
  ring_number varchar(80) NOT NULL CHECK (length(btrim(ring_number)) BETWEEN 1 AND 80),
  bird_name text NOT NULL CHECK (length(btrim(bird_name)) BETWEEN 1 AND 80),
  color text NOT NULL CHECK (length(btrim(color)) BETWEEN 1 AND 40),
  loft_name text NOT NULL CHECK (length(btrim(loft_name)) BETWEEN 1 AND 120),
  sex text CHECK (sex IS NULL OR sex IN ('cock', 'hen')),
  hatch_year integer CHECK (hatch_year IS NULL OR hatch_year BETWEEN 1990 AND 2100),
  nfc_tag varchar(20) COLLATE "C" CHECK (nfc_tag IS NULL OR nfc_tag ~ '^([0-9A-F]{8}|[0-9A-F]{14}|[0-9A-F]{20})$'),
  nfc_read_with text CHECK (nfc_read_with IS NULL OR nfc_read_with IN ('wireless', 'wired', 'phone')),
  photo_path text NOT NULL CHECK (length(photo_path) BETWEEN 3 AND 300),
  status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'retired')),
  created_by uuid DEFAULT auth.uid(),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_pigeons_member ON public.pigeons(member_id);
-- One ring number per club, and one RFID tag per active bird (tags are global).
CREATE UNIQUE INDEX IF NOT EXISTS pigeons_club_ring_key ON public.pigeons (club_id, upper(btrim(ring_number)));
CREATE UNIQUE INDEX IF NOT EXISTS pigeons_active_nfc_tag_key ON public.pigeons (nfc_tag) WHERE nfc_tag IS NOT NULL AND status = 'active';
-- Race entries pick a bird by tapping its RFID tag, so an active bird needs
-- one. NOT VALID: birds bonded earlier without a tag are left as they are
-- until they are edited.
ALTER TABLE public.pigeons DROP CONSTRAINT IF EXISTS pigeons_active_needs_nfc_tag;
ALTER TABLE public.pigeons ADD CONSTRAINT pigeons_active_needs_nfc_tag CHECK (status <> 'active' OR nfc_tag IS NOT NULL) NOT VALID;

-- Tidy values, check the member and the RFID tag.
CREATE OR REPLACE FUNCTION public._pigeon_before_save()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
BEGIN
  NEW.ring_number := upper(btrim(NEW.ring_number));
  NEW.bird_name := btrim(NEW.bird_name);
  NEW.color := btrim(NEW.color);
  NEW.loft_name := btrim(NEW.loft_name);
  NEW.nfc_tag := public.normalize_nfc_uid(NEW.nfc_tag);
  NEW.updated_at := now();
  IF NOT EXISTS (SELECT 1 FROM public.members AS m WHERE m.id = NEW.member_id AND m.club_id = NEW.club_id) THEN
    RAISE EXCEPTION 'Choose a member of this club.' USING ERRCODE = '22023';
  END IF;
  IF NEW.nfc_tag IS NOT NULL AND to_regclass('public.nfc_tags') IS NOT NULL
     AND NOT EXISTS (SELECT 1 FROM public.nfc_tags AS t WHERE t.tag_uid = NEW.nfc_tag) THEN
    RAISE EXCEPTION 'RFID tag % is not registered. Ask the Super Admin to register it first.', NEW.nfc_tag USING ERRCODE = '22023';
  END IF;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS pigeons_before_save ON public.pigeons;
CREATE TRIGGER pigeons_before_save BEFORE INSERT OR UPDATE ON public.pigeons
  FOR EACH ROW EXECUTE FUNCTION public._pigeon_before_save();

ALTER TABLE public.pigeons ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS pigeons_read ON public.pigeons;
CREATE POLICY pigeons_read ON public.pigeons FOR SELECT TO authenticated
  USING ((public.can_manage_club_data() AND club_id = public.current_club_id()) OR member_id = public.current_member_id());
DROP POLICY IF EXISTS pigeons_club_write ON public.pigeons;
CREATE POLICY pigeons_club_write ON public.pigeons FOR ALL TO authenticated
  USING (public.can_manage_club_data() AND club_id = public.current_club_id())
  WITH CHECK (public.can_manage_club_data() AND club_id = public.current_club_id());
GRANT SELECT, INSERT, UPDATE, DELETE ON public.pigeons TO authenticated;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO authenticated;

-- Race entries use a bonded bird. Entries saved before this file keep working.
ALTER TABLE public.race_entries ADD COLUMN IF NOT EXISTS pigeon_id bigint REFERENCES public.pigeons(id) ON DELETE RESTRICT;
CREATE UNIQUE INDEX IF NOT EXISTS race_entries_race_pigeon_key ON public.race_entries (race_id, pigeon_id) WHERE pigeon_id IS NOT NULL;

-- Runs before the other race entry checks (the name sorts first), so the RFID
-- tag copied from the bond is checked like any other.
CREATE OR REPLACE FUNCTION public._race_entry_from_bonded_pigeon()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE
  v_pigeon public.pigeons%ROWTYPE;
  v_race_club bigint;
BEGIN
  IF NEW.pigeon_id IS NULL THEN
    RAISE EXCEPTION 'Choose a bonded bird. Bond the bird (ring, RFID, loft, name, colour and photo) on Band Assignments first.' USING ERRCODE = '22023';
  END IF;
  SELECT p.* INTO v_pigeon FROM public.pigeons AS p WHERE p.id = NEW.pigeon_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'That bonded bird was not found.' USING ERRCODE = '22023'; END IF;
  IF v_pigeon.status <> 'active' THEN
    RAISE EXCEPTION 'Bird % is retired and cannot be entered in a race.', v_pigeon.ring_number USING ERRCODE = '22023';
  END IF;
  IF v_pigeon.nfc_tag IS NULL THEN
    RAISE EXCEPTION 'Bird % has no RFID tag. Add its tag on Band Assignments first.', v_pigeon.ring_number USING ERRCODE = '22023';
  END IF;
  SELECT r.club_id INTO v_race_club FROM public.races AS r WHERE r.id = NEW.race_id;
  IF v_race_club IS DISTINCT FROM v_pigeon.club_id THEN
    RAISE EXCEPTION 'Bird % belongs to another club.', v_pigeon.ring_number USING ERRCODE = '22023';
  END IF;
  IF NEW.member_id IS NOT NULL AND NEW.member_id <> v_pigeon.member_id THEN
    RAISE EXCEPTION 'Bird % is bonded to another member.', v_pigeon.ring_number USING ERRCODE = '22023';
  END IF;
  NEW.member_id := v_pigeon.member_id;
  NEW.pigeon_ring := v_pigeon.ring_number;
  IF v_pigeon.nfc_tag IS NOT NULL THEN
    NEW.nfc_tag := v_pigeon.nfc_tag;
    NEW.nfc_read_with := coalesce(NEW.nfc_read_with, v_pigeon.nfc_read_with);
  END IF;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS race_entries_0_bonded_pigeon ON public.race_entries;
CREATE TRIGGER race_entries_0_bonded_pigeon BEFORE INSERT OR UPDATE OF pigeon_id ON public.race_entries
  FOR EACH ROW EXECUTE FUNCTION public._race_entry_from_bonded_pigeon();

-- Private photo bucket and who may use it (skipped where Supabase Storage is not installed).
DO $$
BEGIN
  IF to_regclass('storage.buckets') IS NULL OR to_regclass('storage.objects') IS NULL THEN
    RAISE NOTICE 'Supabase Storage not found: skipping the pigeon-photos bucket.';
    RETURN;
  END IF;
  INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
  VALUES ('pigeon-photos', 'pigeon-photos', false, 3145728, ARRAY['image/jpeg', 'image/png', 'image/webp'])
  ON CONFLICT (id) DO UPDATE SET public = false, file_size_limit = EXCLUDED.file_size_limit, allowed_mime_types = EXCLUDED.allowed_mime_types;

  EXECUTE 'DROP POLICY IF EXISTS pigeon_photos_read ON storage.objects';
  EXECUTE $p$CREATE POLICY pigeon_photos_read ON storage.objects FOR SELECT TO authenticated USING (
    bucket_id = 'pigeon-photos' AND (
      (public.can_manage_club_data() AND (storage.foldername(name))[1] = public.current_club_id()::text)
      OR EXISTS (SELECT 1 FROM public.pigeons AS p WHERE p.photo_path = storage.objects.name AND p.member_id = public.current_member_id())))$p$;
  EXECUTE 'DROP POLICY IF EXISTS pigeon_photos_club_insert ON storage.objects';
  EXECUTE $p$CREATE POLICY pigeon_photos_club_insert ON storage.objects FOR INSERT TO authenticated WITH CHECK (
    bucket_id = 'pigeon-photos' AND public.can_manage_club_data() AND (storage.foldername(name))[1] = public.current_club_id()::text)$p$;
  EXECUTE 'DROP POLICY IF EXISTS pigeon_photos_club_update ON storage.objects';
  EXECUTE $p$CREATE POLICY pigeon_photos_club_update ON storage.objects FOR UPDATE TO authenticated USING (
    bucket_id = 'pigeon-photos' AND public.can_manage_club_data() AND (storage.foldername(name))[1] = public.current_club_id()::text)$p$;
  EXECUTE 'DROP POLICY IF EXISTS pigeon_photos_club_delete ON storage.objects';
  EXECUTE $p$CREATE POLICY pigeon_photos_club_delete ON storage.objects FOR DELETE TO authenticated USING (
    bucket_id = 'pigeon-photos' AND public.can_manage_club_data() AND (storage.foldername(name))[1] = public.current_club_id()::text)$p$;
END $$;

