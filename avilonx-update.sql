-- Saves the video a member uploaded for one of their clocks. Returns the path of
-- the video it replaces (or null), so the website can delete that file.
CREATE OR REPLACE FUNCTION public.member_save_clock_video(p_clock_id bigint, p_path text, p_duration numeric, p_size bigint)
RETURNS jsonb LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path = '' AS $$
DECLARE
  v_member_id bigint := public.current_member_id();
  v_club_id bigint;
  v_old text;
  v_found boolean;
BEGIN
  IF v_member_id IS NULL THEN RAISE EXCEPTION 'Member account required.' USING ERRCODE = '42501'; END IF;
  SELECT r.club_id INTO v_club_id
  FROM public.clock_events AS c
  JOIN public.race_entries AS e ON e.id = c.race_entry_id
  JOIN public.races AS r ON r.id = e.race_id
  WHERE c.id = p_clock_id AND e.member_id = v_member_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'This clocking is not one of your pigeons.' USING ERRCODE = '42501'; END IF;
  IF p_path IS NULL OR p_path NOT LIKE v_club_id || '/' || v_member_id || '/' || p_clock_id || '/%' OR position('..' IN p_path) > 0 THEN
    RAISE EXCEPTION 'The video was not saved in your folder. Try again.' USING ERRCODE = '22023';
  END IF;
  IF p_duration IS NULL OR p_duration <= 0 OR p_duration > 31 THEN
    RAISE EXCEPTION 'The video must be 30 seconds or shorter.' USING ERRCODE = '22023';
  END IF;
  IF p_size IS NULL OR p_size <= 0 OR p_size > 52428800 THEN
    RAISE EXCEPTION 'The video must be 50 MB or smaller.' USING ERRCODE = '22023';
  END IF;
  IF to_regclass('storage.objects') IS NOT NULL THEN
    EXECUTE 'SELECT EXISTS (SELECT 1 FROM storage.objects WHERE bucket_id = $1 AND name = $2)' INTO v_found USING 'clock-videos', p_path;
    IF NOT v_found THEN RAISE EXCEPTION 'The video upload did not finish. Try again.' USING ERRCODE = '22023'; END IF;
  END IF;

  SELECT v.storage_path INTO v_old FROM public.clock_videos AS v WHERE v.clock_event_id = p_clock_id;
  INSERT INTO public.clock_videos (clock_event_id, member_id, club_id, storage_path, duration_seconds, size_bytes)
  VALUES (p_clock_id, v_member_id, v_club_id, p_path, round(p_duration, 2), p_size)
  ON CONFLICT (clock_event_id) DO UPDATE
    SET storage_path = EXCLUDED.storage_path, duration_seconds = EXCLUDED.duration_seconds,
        size_bytes = EXCLUDED.size_bytes, created_at = now();
  RETURN jsonb_build_object('status', 'saved', 'replaced_path', CASE WHEN v_old IS DISTINCT FROM p_path THEN v_old END);
END;
$$;
REVOKE ALL ON FUNCTION public.member_save_clock_video(bigint, text, numeric, bigint) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.member_save_clock_video(bigint, text, numeric, bigint) TO authenticated;

-- Private video bucket and who may use it (skipped where Supabase Storage is not installed).
DO $$
BEGIN
  IF to_regclass('storage.buckets') IS NULL OR to_regclass('storage.objects') IS NULL THEN
    RAISE NOTICE 'Supabase Storage not found: skipping the clock-videos bucket.';
    RETURN;
  END IF;
  INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
  VALUES ('clock-videos', 'clock-videos', false, 52428800,
