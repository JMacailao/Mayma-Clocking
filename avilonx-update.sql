CREATE OR REPLACE FUNCTION public._audit_change()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE
  v_row jsonb := CASE WHEN TG_OP = 'DELETE' THEN to_jsonb(OLD) ELSE to_jsonb(NEW) END;
  v_club bigint;
  v_name text;
BEGIN
  -- Skip updates that change nothing.
  IF TG_OP = 'UPDATE' AND to_jsonb(OLD) = to_jsonb(NEW) THEN RETURN NULL; END IF;
  v_club := nullif(v_row->>'club_id', '')::bigint;
  IF v_club IS NULL AND v_row ? 'race_id' THEN
    SELECT r.club_id INTO v_club FROM public.races AS r WHERE r.id = (v_row->>'race_id')::bigint;
  END IF;
  IF v_club IS NULL AND v_row ? 'race_entry_id' THEN
    SELECT r.club_id INTO v_club FROM public.race_entries AS e JOIN public.races AS r ON r.id = e.race_id
    WHERE e.id = (v_row->>'race_entry_id')::bigint;
  END IF;
  SELECT p.username INTO v_name FROM public.app_profiles AS p WHERE p.id = auth.uid();
  INSERT INTO public.audit_log (club_id, table_name, row_id, action, changed_by, changed_by_name, old_data, new_data)
  VALUES (v_club, TG_TABLE_NAME, nullif(v_row->>'id', '')::bigint, lower(TG_OP), auth.uid(),
    coalesce(v_name, CASE WHEN auth.uid() IS NULL THEN 'RFID reader / system' ELSE 'Unknown account' END),
    CASE WHEN TG_OP = 'INSERT' THEN NULL ELSE to_jsonb(OLD) END,
    CASE WHEN TG_OP = 'DELETE' THEN NULL ELSE to_jsonb(NEW) END);
  RETURN NULL;
END;
$$;
REVOKE ALL ON FUNCTION public._audit_change() FROM PUBLIC, anon, authenticated;

