-- Tags read by Register-mode readers since p_after_id, for the pages that fill
-- in an NFC tag field. Club admins and staff see their club's readers; the
-- Super Admin (who registers tags for every club) sees all readers.
CREATE OR REPLACE FUNCTION public.rfid_recent_scans(p_after_id bigint DEFAULT NULL)
RETURNS TABLE (id bigint, device_name text, tag_uid text, scanned_at timestamptz)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = '' AS $$
DECLARE
  v_super boolean := public.is_superadmin();
BEGIN
  IF NOT v_super AND NOT public.can_manage_club_data() THEN
    RAISE EXCEPTION 'Club administrator, staff or Super Admin account required.' USING ERRCODE = '42501';
  END IF;
  RETURN QUERY
    SELECT s.id, d.name, s.tag_uid::text, s.scanned_at
    FROM public.rfid_device_scans AS s JOIN public.rfid_devices AS d ON d.id = s.device_id
    WHERE s.mode = 'register'
      AND (v_super OR d.club_id = public.current_club_id())
      AND (p_after_id IS NULL OR s.id > p_after_id)
      AND s.scanned_at > now() - interval '2 minutes'
    ORDER BY s.id DESC
    LIMIT 20;
END;
$$;

