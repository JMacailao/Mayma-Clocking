  IF NEW.barcode IS NULL OR btrim(NEW.barcode) = '' THEN
    SELECT c.rfid_entry_sticker INTO v_rule FROM public.races AS r JOIN public.clubs AS c ON c.id = r.club_id WHERE r.id = NEW.race_id;
