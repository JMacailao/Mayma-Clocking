CREATE OR REPLACE FUNCTION public._new_sticker_scratch_code(p_number text)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
  v_code text;
BEGIN
  LOOP
    v_code := lpad(((('x' || substr(md5(gen_random_uuid()::text), 1, 15))::bit(60)::bigint % 1000000))::text, 6, '0');
