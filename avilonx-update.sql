-- ============================================================================
-- password-reset.sql
-- ============================================================================
-- AvilonX Clocking: "Forgot password?" by email (Gmail).
--
-- Each account can have a recovery email. On the sign-in page, "Forgot
-- password?" asks for the username; the avilonx-password-reset Edge Function
-- then emails a one-time link (30 minutes) to that address, and the link's page
-- sets a new password. Usernames stay the way to sign in.
--   * Everyone sets their own recovery email (Club settings, member Settings).
--   * The Super Admin sets a club administrator's; a club administrator sets a member's.
-- Only the Edge Function (service role) can start or finish a reset.
--
-- Run after multi-club.sql. Safe to run again.

ALTER TABLE public.app_profiles ADD COLUMN IF NOT EXISTS recovery_email text;
ALTER TABLE public.app_profiles DROP CONSTRAINT IF EXISTS app_profiles_recovery_email_check;
ALTER TABLE public.app_profiles ADD CONSTRAINT app_profiles_recovery_email_check
  CHECK (recovery_email IS NULL OR (length(recovery_email) <= 254 AND recovery_email ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$'));

CREATE TABLE IF NOT EXISTS public.password_resets (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  token_hash text NOT NULL UNIQUE,
  expires_at timestamptz NOT NULL,
  used_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_password_resets_user ON public.password_resets(user_id, created_at);
ALTER TABLE public.password_resets ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.password_resets FROM anon, authenticated;

CREATE OR REPLACE FUNCTION public._clean_email(p_email text)
RETURNS text LANGUAGE plpgsql IMMUTABLE SET search_path = '' AS $$
DECLARE v text := lower(btrim(coalesce(p_email, '')));
BEGIN
  IF v = '' THEN RETURN NULL; END IF;
  IF length(v) > 254 OR v !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' THEN
    RAISE EXCEPTION 'Enter a valid email address, e.g. name@gmail.com.' USING ERRCODE = '22023';
  END IF;
  RETURN v;
END;
$$;

-- Your own recovery email (empty removes it).
CREATE OR REPLACE FUNCTION public.set_my_recovery_email(p_email text)
RETURNS text LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path = '' AS $$
DECLARE v text := public._clean_email(p_email);
BEGIN
  IF (SELECT auth.uid()) IS NULL THEN RAISE EXCEPTION 'Sign in first.' USING ERRCODE = '42501'; END IF;
  UPDATE public.app_profiles SET recovery_email = v WHERE id = (SELECT auth.uid());
  RETURN v;
END;
$$;
REVOKE ALL ON FUNCTION public.set_my_recovery_email(text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.set_my_recovery_email(text) TO authenticated;

-- Super Admin: the recovery email of a club's administrator account(s).
CREATE OR REPLACE FUNCTION public.superadmin_set_club_admin_email(p_club_id bigint, p_email text)
RETURNS text LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path = '' AS $$
DECLARE v text := public._clean_email(p_email);
BEGIN
  IF NOT public.is_superadmin() THEN RAISE EXCEPTION 'Super Admin account required.' USING ERRCODE = '42501'; END IF;
  UPDATE public.app_profiles SET recovery_email = v WHERE club_id = p_club_id AND role = 'admin';
  IF NOT FOUND THEN RAISE EXCEPTION 'This club has no administrator account.' USING ERRCODE = '22023'; END IF;
  RETURN v;
END;
$$;
REVOKE ALL ON FUNCTION public.superadmin_set_club_admin_email(bigint, text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.superadmin_set_club_admin_email(bigint, text) TO authenticated;

-- Club administrator: a member's recovery email.
CREATE OR REPLACE FUNCTION public.admin_set_member_email(p_member_id bigint, p_email text)
RETURNS text LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path = '' AS $$
DECLARE v text := public._clean_email(p_email);
BEGIN
  IF NOT public.is_app_admin() THEN RAISE EXCEPTION 'Club administrator account required.' USING ERRCODE = '42501'; END IF;
