-- A reader's job follows from who uses it:
--   club admin (no member)  -> register: taps fill the Race entries tag field, never clock
--   one member (loft clock) -> clock: taps clock only that member's own pigeons, never register
-- The trigger keeps mode in step on every change (also when a member is deleted
-- and member_id is cleared).
CREATE OR REPLACE FUNCTION public._rfid_device_mode_from_member()
RETURNS trigger LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
  NEW.mode := CASE WHEN NEW.member_id IS NULL THEN 'register' ELSE 'clock' END;
  RETURN NEW;
END;
$$;
