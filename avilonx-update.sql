  member_id bigint NOT NULL REFERENCES public.members(id) ON DELETE CASCADE,
  club_id bigint NOT NULL,
  storage_path text NOT NULL,
  duration_seconds numeric(6,2),
  size_bytes bigint,
  created_at timestamptz NOT NULL DEFAULT now()
);
