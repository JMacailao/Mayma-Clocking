CREATE TRIGGER rfid_devices_mode_from_member BEFORE INSERT OR UPDATE ON public.rfid_devices
  FOR EACH ROW EXECUTE FUNCTION public._rfid_device_mode_from_member();
UPDATE public.rfid_devices SET mode = mode;  -- bring readers saved earlier into line

