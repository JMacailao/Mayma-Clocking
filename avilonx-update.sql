-- AvilonX Clocking: a short video of each clocking.
--
-- After clocking, a member can add a short video (up to 30 seconds, 50 MB) of
-- the pigeon arriving. It is kept in a private Supabase Storage bucket,
-- "clock-videos", in a folder per club and member:
--   <club id>/<member id>/<clock id>/<time>.<ext>
-- The member sees their own videos; the club's administrators and staff see
-- every video of their club (Show up). One video per clock: a new one replaces
-- the old one.
--
-- Run after show-up.sql and before race-day.sql. Safe to run again.

