-- ============================================================================
-- rfid-devices.sql
-- ============================================================================
-- AvilonX Clocking: external RFID readers (ESP8266 + RC522).
--
-- The Super Admin registers each reader by its serial number (the board's
-- Wi-Fi MAC address), assigns it to a club and gets a device key. The reader sends every tag it reads,
-- with its serial and key, to public.device_rfid_scan(). Readers that are not
-- registered, or send the wrong key, are refused.
--
-- Each reader has a mode:
--   register  every tap is passed to the Race entries and Register NFC pages,
--             which fill the NFC tag field with it.
--   clock     every tap clocks that tag's pigeon in an open race of the club,
--             at Supabase server time, like a member tapping the tag.
-- The mode follows from who uses the reader, chosen by the Super Admin (the
-- only one who can register, move, re-key or delete readers):
--   the club admin  -> register only (never clocks)
--   one member      -> clock only, and only that member's own pigeons' tags
--
-- Run after nfc-tags.sql. Safe to run again.

DO $$
BEGIN
  IF to_regprocedure('public.normalize_nfc_uid(text)') IS NULL
     OR to_regprocedure('public._clock_receipt_details(bigint,bigint)') IS NULL THEN
    RAISE EXCEPTION 'Run nfc-tags.sql (and sticker-barcodes.sql) before rfid-devices.sql.';
  END IF;
