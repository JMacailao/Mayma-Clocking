-- AvilonX Clocking: "Forgot password?" by email (Gmail).
--
-- Each account can have a recovery email. On the sign-in page, "Forgot
-- password?" asks for the username; the avilonx-password-reset Edge Function
-- then emails a one-time link (30 minutes) to that address, and the link's page
-- sets a new password. Usernames stay the way to sign in.
--   * Everyone sets their own recovery email (Club settings, member Settings).
--   * The Super Admin sets a club administrator's; a club administrator sets a member's.
-- Only the Edge Function (service role) can start or finish a reset.
--
-- Run after multi-club.sql. Safe to run again.

ALTER TABLE public.app_profiles ADD COLUMN IF NOT EXISTS recovery_email text;
ALTER TABLE public.app_profiles DROP CONSTRAINT IF EXISTS app_profiles_recovery_email_check;
ALTER TABLE public.app_profiles ADD CONSTRAINT app_profiles_recovery_email_check
  CHECK (recovery_email IS NULL OR (length(recovery_email) <= 254 AND recovery_email ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$'));

CREATE TABLE IF NOT EXISTS public.password_resets (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  token_hash text NOT NULL UNIQUE,
  expires_at timestamptz NOT NULL,
  used_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_password_resets_user ON public.password_resets(user_id, created_at);
ALTER TABLE public.password_resets ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.password_resets FROM anon, authenticated;

CREATE OR REPLACE FUNCTION public._clean_email(p_email text)
RETURNS text LANGUAGE plpgsql IMMUTABLE SET search_path = '' AS $$
DECLARE v text := lower(btrim(coalesce(p_email, '')));
BEGIN
  IF v = '' THEN RETURN NULL; END IF;
  IF length(v) > 254 OR v !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' THEN
    RAISE EXCEPTION 'Enter a valid email address, e.g. name@gmail.com.' USING ERRCODE = '22023';
  END IF;
  RETURN v;
END;
$$;

-- Your own recovery email (empty removes it).
CREATE OR REPLACE FUNCTION public.set_my_recovery_email(p_email text)
RETURNS text LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path = '' AS $$
DECLARE v text := public._clean_email(p_email);
BEGIN
  IF (SELECT auth.uid()) IS NULL THEN RAISE EXCEPTION 'Sign in first.' USING ERRCODE = '42501'; END IF;
  UPDATE public.app_profiles SET recovery_email = v WHERE id = (SELECT auth.uid());
  RETURN v;
END;
$$;
REVOKE ALL ON FUNCTION public.set_my_recovery_email(text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.set_my_recovery_email(text) TO authenticated;

-- Super Admin: the recovery email of a club's administrator account(s).
CREATE OR REPLACE FUNCTION public.superadmin_set_club_admin_email(p_club_id bigint, p_email text)
RETURNS text LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path = '' AS $$
DECLARE v text := public._clean_email(p_email);
BEGIN
  IF NOT public.is_superadmin() THEN RAISE EXCEPTION 'Super Admin account required.' USING ERRCODE = '42501'; END IF;
  UPDATE public.app_profiles SET recovery_email = v WHERE club_id = p_club_id AND role = 'admin';
  IF NOT FOUND THEN RAISE EXCEPTION 'This club has no administrator account.' USING ERRCODE = '22023'; END IF;
  RETURN v;
END;
$$;
REVOKE ALL ON FUNCTION public.superadmin_set_club_admin_email(bigint, text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.superadmin_set_club_admin_email(bigint, text) TO authenticated;

-- Club administrator: a member's recovery email.
CREATE OR REPLACE FUNCTION public.admin_set_member_email(p_member_id bigint, p_email text)
RETURNS text LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path = '' AS $$
DECLARE v text := public._clean_email(p_email);
BEGIN
  IF NOT public.is_app_admin() THEN RAISE EXCEPTION 'Club administrator account required.' USING ERRCODE = '42501'; END IF;
  UPDATE public.app_profiles SET recovery_email = v
   WHERE member_id = p_member_id AND role = 'member' AND club_id = public.current_club_id();
  IF NOT FOUND THEN RAISE EXCEPTION 'This member has no login yet.' USING ERRCODE = '22023'; END IF;
  RETURN v;
END;
$$;
REVOKE ALL ON FUNCTION public.admin_set_member_email(bigint, text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.admin_set_member_email(bigint, text) TO authenticated;

-- For the Edge Function only: a new one-time link for this username, or null
-- (unknown username, no recovery email, inactive, or 3 links in the last hour).
CREATE OR REPLACE FUNCTION public._password_reset_start(p_username text)
RETURNS jsonb LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path = '' AS $$
DECLARE
  v_profile public.app_profiles%ROWTYPE;
  v_token text := encode(extensions.gen_random_bytes(32), 'hex');
BEGIN
  SELECT p.* INTO v_profile FROM public.app_profiles AS p
   WHERE p.username = lower(btrim(coalesce(p_username, ''))) AND p.is_active IS NOT FALSE AND p.recovery_email IS NOT NULL;
  IF NOT FOUND THEN RETURN NULL; END IF;
  IF (SELECT count(*) FROM public.password_resets AS r WHERE r.user_id = v_profile.id AND r.created_at > now() - interval '1 hour') >= 3 THEN
    RETURN NULL;
  END IF;
  INSERT INTO public.password_resets (user_id, token_hash, expires_at)
  VALUES (v_profile.id, encode(extensions.digest(v_token, 'sha256'), 'hex'), now() + interval '30 minutes');
  RETURN jsonb_build_object('email', v_profile.recovery_email, 'username', v_profile.username, 'token', v_token);
END;
$$;
REVOKE ALL ON FUNCTION public._password_reset_start(text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public._password_reset_start(text) TO service_role;

-- For the Edge Function only: sets the new password if the link is valid.
CREATE OR REPLACE FUNCTION public._password_reset_finish(p_token text, p_password text)
RETURNS jsonb LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_reset public.password_resets%ROWTYPE;
BEGIN
  IF p_password IS NULL OR length(p_password) < 8 THEN
    RETURN jsonb_build_object('ok', false, 'message', 'Use at least 8 characters.');
  END IF;
  SELECT r.* INTO v_reset FROM public.password_resets AS r
   WHERE r.token_hash = encode(extensions.digest(coalesce(p_token, ''), 'sha256'), 'hex') FOR UPDATE;
  IF NOT FOUND OR v_reset.used_at IS NOT NULL OR v_reset.expires_at < now() THEN
    RETURN jsonb_build_object('ok', false, 'message', 'This link has expired or was already used. Ask for a new one.');
  END IF;
  UPDATE auth.users SET encrypted_password = extensions.crypt(p_password, extensions.gen_salt('bf')), updated_at = now() WHERE id = v_reset.user_id;
  UPDATE public.password_resets SET used_at = now() WHERE user_id = v_reset.user_id AND used_at IS NULL;
  RETURN jsonb_build_object('ok', true, 'username', (SELECT p.username FROM public.app_profiles AS p WHERE p.id = v_reset.user_id));
END;
$$;
REVOKE ALL ON FUNCTION public._password_reset_finish(text, text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public._password_reset_finish(text, text) TO service_role;

