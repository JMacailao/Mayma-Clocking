-- AvilonX Clocking: results on Telegram for loft reader owners.
--
-- Members who own an ESP8266 loft reader (a reader registered to them) can
-- connect their Telegram on Settings → Telegram. Each time one of their pigeons
-- is clocked (by any means), the database writes the message here and asks the
-- "avilonx-telegram" Supabase Edge Function to send it. The bot key is kept in
-- the Edge Function, never in the website or the database.
--
-- Setup (Super Admin → Telegram bot) is explained on that page and in
-- docs/TELEGRAM.md. Run after rfid-devices.sql. Safe to run again.

DO $$
BEGIN
  -- pg_net lets the database call the Edge Function (available on Supabase).
  CREATE EXTENSION IF NOT EXISTS pg_net;
EXCEPTION WHEN OTHERS THEN
  RAISE NOTICE 'pg_net is not available here: Telegram messages are queued but not sent.';
END $$;

-- The bot and the Edge Function (one row, Super Admin only).
CREATE TABLE IF NOT EXISTS public.telegram_settings (
  id integer PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  bot_username text NOT NULL DEFAULT '' CHECK (bot_username ~ '^[A-Za-z0-9_]{0,40}$'),
  function_url text NOT NULL DEFAULT '' CHECK (function_url = '' OR function_url ~ '^https://'),
  secret text NOT NULL DEFAULT '',
  updated_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.telegram_settings ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.telegram_settings FROM PUBLIC, anon, authenticated;

-- Members: their Telegram chat, and the one-time code used to connect it.
ALTER TABLE public.members ADD COLUMN IF NOT EXISTS telegram_chat_id bigint;
ALTER TABLE public.members ADD COLUMN IF NOT EXISTS telegram_linked_at timestamptz;
ALTER TABLE public.members ADD COLUMN IF NOT EXISTS telegram_link_code text;
ALTER TABLE public.members ADD COLUMN IF NOT EXISTS telegram_link_expires_at timestamptz;

-- Messages waiting to be sent (and sent ones, for checking).
CREATE TABLE IF NOT EXISTS public.telegram_outbox (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_id bigint REFERENCES public.members(id) ON DELETE CASCADE,
  chat_id bigint NOT NULL,
  text text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  sent_at timestamptz,
  error text
);
ALTER TABLE public.telegram_outbox ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.telegram_outbox FROM PUBLIC, anon, authenticated;

-- Owns a loft reader = a reader registered to this member.
CREATE OR REPLACE FUNCTION public._member_owns_reader(p_member_id bigint)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = '' AS $$
  SELECT EXISTS (SELECT 1 FROM public.rfid_devices AS d WHERE d.member_id = p_member_id);
$$;
REVOKE ALL ON FUNCTION public._member_owns_reader(bigint) FROM PUBLIC, anon, authenticated;

-- ---- Super Admin ------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.superadmin_get_telegram()
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = '' AS $$
DECLARE s public.telegram_settings%ROWTYPE;
BEGIN
  IF NOT public.is_superadmin() THEN RAISE EXCEPTION 'Super Admin only.' USING ERRCODE = '42501'; END IF;
  SELECT * INTO s FROM public.telegram_settings WHERE id = 1;
  RETURN jsonb_build_object('bot_username', coalesce(s.bot_username, ''), 'function_url', coalesce(s.function_url, ''), 'secret', coalesce(s.secret, ''),
    'linked_members', (SELECT count(*) FROM public.members WHERE telegram_chat_id IS NOT NULL),
    'sent', (SELECT count(*) FROM public.telegram_outbox WHERE sent_at IS NOT NULL),
    'failed', (SELECT count(*) FROM public.telegram_outbox WHERE error IS NOT NULL),
    'last_error', (SELECT error FROM public.telegram_outbox WHERE error IS NOT NULL ORDER BY id DESC LIMIT 1));
END;
$$;

CREATE OR REPLACE FUNCTION public.superadmin_set_telegram(p_bot_username text, p_function_url text, p_new_secret boolean DEFAULT false)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
BEGIN
  IF NOT public.is_superadmin() THEN RAISE EXCEPTION 'Super Admin only.' USING ERRCODE = '42501'; END IF;
  INSERT INTO public.telegram_settings (id, bot_username, function_url, secret)
  VALUES (1, regexp_replace(coalesce(p_bot_username, ''), '^@', ''), btrim(coalesce(p_function_url, '')), encode(extensions.gen_random_bytes(24), 'hex'))
  ON CONFLICT (id) DO UPDATE SET bot_username = EXCLUDED.bot_username, function_url = EXCLUDED.function_url,
    secret = CASE WHEN p_new_secret OR public.telegram_settings.secret = '' THEN EXCLUDED.secret ELSE public.telegram_settings.secret END,
    updated_at = now();
  RETURN public.superadmin_get_telegram();
END;
$$;

-- ---- Members ----------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.member_telegram_status()
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_member bigint := public.current_member_id(); m public.members%ROWTYPE;
BEGIN
  IF v_member IS NULL THEN RETURN jsonb_build_object('eligible', false); END IF;
  SELECT * INTO m FROM public.members WHERE id = v_member;
  RETURN jsonb_build_object('eligible', public._member_owns_reader(v_member), 'linked', m.telegram_chat_id IS NOT NULL, 'linked_at', m.telegram_linked_at,
    'ready', EXISTS (SELECT 1 FROM public.telegram_settings WHERE id = 1 AND bot_username <> '' AND function_url <> ''));
END;
$$;

-- A one-time link (valid 30 minutes) that opens the bot and connects this member.
CREATE OR REPLACE FUNCTION public.member_telegram_link()
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_member bigint := public.current_member_id(); v_bot text; v_code text := encode(extensions.gen_random_bytes(12), 'hex');
BEGIN
  IF v_member IS NULL OR NOT public._member_owns_reader(v_member) THEN
    RAISE EXCEPTION 'Telegram results are for members with a loft RFID reader.' USING ERRCODE = '42501';
  END IF;
  SELECT bot_username INTO v_bot FROM public.telegram_settings WHERE id = 1 AND bot_username <> '' AND function_url <> '';
  IF v_bot IS NULL THEN RAISE EXCEPTION 'Telegram is not set up yet. Ask the AvilonX Super Admin.' USING ERRCODE = '22023'; END IF;
  UPDATE public.members SET telegram_link_code = v_code, telegram_link_expires_at = now() + interval '30 minutes' WHERE id = v_member;
  RETURN jsonb_build_object('url', 'https://t.me/' || v_bot || '?start=' || v_code, 'bot_username', v_bot);
END;
$$;

CREATE OR REPLACE FUNCTION public.member_telegram_unlink()
RETURNS void LANGUAGE sql SECURITY DEFINER SET search_path = '' AS $$
  UPDATE public.members SET telegram_chat_id = NULL, telegram_linked_at = NULL, telegram_link_code = NULL WHERE id = public.current_member_id();
$$;

-- ---- Called by the Edge Function (service role only) ------------------------------
CREATE OR REPLACE FUNCTION public.telegram_link_by_code(p_code text, p_chat_id bigint)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE m public.members%ROWTYPE;
BEGIN
  SELECT * INTO m FROM public.members WHERE telegram_link_code = p_code AND telegram_link_expires_at > now();
  IF NOT FOUND OR p_code IS NULL OR length(p_code) < 16 THEN RETURN jsonb_build_object('ok', false); END IF;
  UPDATE public.members SET telegram_chat_id = p_chat_id, telegram_linked_at = now(), telegram_link_code = NULL, telegram_link_expires_at = NULL WHERE id = m.id;
  RETURN jsonb_build_object('ok', true, 'member', m.full_name);
END;
$$;

CREATE OR REPLACE FUNCTION public.telegram_unlink_chat(p_chat_id bigint)
RETURNS integer LANGUAGE sql SECURITY DEFINER SET search_path = '' AS $$
  WITH done AS (UPDATE public.members SET telegram_chat_id = NULL, telegram_linked_at = NULL WHERE telegram_chat_id = p_chat_id RETURNING 1)
  SELECT count(*)::integer FROM done;
$$;

CREATE OR REPLACE FUNCTION public.telegram_take_message(p_id bigint)
RETURNS jsonb LANGUAGE sql SECURITY DEFINER SET search_path = '' AS $$
  SELECT jsonb_build_object('chat_id', o.chat_id, 'text', o.text) FROM public.telegram_outbox AS o WHERE o.id = p_id AND o.sent_at IS NULL;
$$;

CREATE OR REPLACE FUNCTION public.telegram_mark_sent(p_id bigint, p_error text DEFAULT NULL)
RETURNS void LANGUAGE sql SECURITY DEFINER SET search_path = '' AS $$
  UPDATE public.telegram_outbox SET sent_at = CASE WHEN p_error IS NULL THEN now() ELSE sent_at END, error = left(p_error, 300) WHERE id = p_id;
$$;

REVOKE ALL ON FUNCTION public.superadmin_get_telegram(), public.superadmin_set_telegram(text, text, boolean), public.member_telegram_status(),
  public.member_telegram_link(), public.member_telegram_unlink(), public.telegram_link_by_code(text, bigint), public.telegram_unlink_chat(bigint),
  public.telegram_take_message(bigint), public.telegram_mark_sent(bigint, text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.superadmin_get_telegram(), public.superadmin_set_telegram(text, text, boolean), public.member_telegram_status(),
  public.member_telegram_link(), public.member_telegram_unlink() TO authenticated;
-- Only the Edge Function (service role) links chats and sends messages.
REVOKE ALL ON FUNCTION public.telegram_link_by_code(text, bigint), public.telegram_unlink_chat(bigint),
  public.telegram_take_message(bigint), public.telegram_mark_sent(bigint, text) FROM authenticated;
GRANT EXECUTE ON FUNCTION public.telegram_link_by_code(text, bigint), public.telegram_unlink_chat(bigint),
  public.telegram_take_message(bigint), public.telegram_mark_sent(bigint, text) TO service_role;

-- ---- A clock is saved: message the owner (if they own a reader and connected Telegram)
CREATE OR REPLACE FUNCTION public._telegram_on_clock()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE
  e public.race_entries%ROWTYPE; r public.races%ROWTYPE; m public.members%ROWTYPE; s public.telegram_settings%ROWTYPE;
  v_seconds numeric; v_text text; v_id bigint; v_how text;
BEGIN
  SELECT * INTO e FROM public.race_entries WHERE id = NEW.race_entry_id;
  IF NOT FOUND THEN RETURN NULL; END IF;
  SELECT * INTO m FROM public.members WHERE id = e.member_id;
  IF m.telegram_chat_id IS NULL OR NOT public._member_owns_reader(m.id) THEN RETURN NULL; END IF;
  SELECT * INTO r FROM public.races WHERE id = e.race_id;
  v_seconds := CASE WHEN r.release_at_utc IS NOT NULL AND NEW.received_at_utc > r.release_at_utc THEN extract(epoch FROM NEW.received_at_utc - r.release_at_utc) END;
  v_how := CASE WHEN NEW.source = 'barcode' THEN 'Sticker' WHEN NEW.source = 'admin_manual' THEN 'Club'
                WHEN NEW.time_source = 'reader' THEN 'Loft RFID reader' ELSE 'NFC tag' END;
  v_text := '🕊 ' || coalesce(e.pigeon_ring, NEW.pigeon_ring)
    || CASE WHEN cardinality(e.remarks) > 0 THEN ' ' || array_to_string(e.remarks, '/') ELSE '' END
    || ' was clocked' || E'\n' || 'Race: ' || r.name
    || E'\n' || 'Time: ' || to_char(NEW.received_at_utc + interval '8 hours', 'Mon DD, HH12:MI:SS AM') || ' (PH)'
    || CASE WHEN v_seconds IS NOT NULL THEN E'\n' || 'Flight: ' || to_char(make_interval(secs => round(v_seconds)), 'HH24:MI:SS')
         || E'\n' || 'Speed: ' || to_char(e.distance_m * 60 / v_seconds, 'FM999,999,990.000') || ' m/min' ELSE '' END
    || E'\n' || 'Clocked with: ' || v_how
    || E'\n\n' || 'Bring the pigeon to the club for Show up before the race is closed. Results are provisional until the club verifies them.';
  INSERT INTO public.telegram_outbox (member_id, chat_id, text) VALUES (m.id, m.telegram_chat_id, v_text) RETURNING id INTO v_id;
  -- Ask the Edge Function to send it now (pg_net calls it in the background).
  SELECT * INTO s FROM public.telegram_settings WHERE id = 1;
  IF s.function_url <> '' AND to_regnamespace('net') IS NOT NULL THEN
    BEGIN
      EXECUTE 'SELECT net.http_post(url := $1, body := $2, headers := $3)'
        USING s.function_url, jsonb_build_object('outbox_id', v_id), jsonb_build_object('Content-Type', 'application/json', 'Authorization', 'Bearer ' || s.secret);
    EXCEPTION WHEN OTHERS THEN
      UPDATE public.telegram_outbox SET error = left('Could not call the Telegram function: ' || SQLERRM, 300) WHERE id = v_id;
    END;
  END IF;
  RETURN NULL;
EXCEPTION WHEN OTHERS THEN
  -- A Telegram problem must never stop a clock from being saved.
  RAISE WARNING 'Telegram message not queued: %', SQLERRM;
  RETURN NULL;
END;
$$;
REVOKE ALL ON FUNCTION public._telegram_on_clock() FROM PUBLIC, anon, authenticated;
DROP TRIGGER IF EXISTS zz_telegram_on_clock ON public.clock_events;
CREATE TRIGGER zz_telegram_on_clock AFTER INSERT ON public.clock_events
  FOR EACH ROW EXECUTE FUNCTION public._telegram_on_clock();

