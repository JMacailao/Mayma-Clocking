-- AvilonX Clocking: push notifications on the website and the Android app.
--
-- Anyone signed in can turn on notifications for a phone or computer on
-- Settings → Notifications. Then:
--   * members: "PH-1 was clocked" for their own pigeons, and "New race open"
--     when the club opens a race;
--   * club administrators and staff: every arrival in their club on race day.
-- The database queues each notification in push_outbox and asks the
-- "avilonx-push" Supabase Edge Function to send it (Web Push). The Edge Function
-- makes its own keys the first time it is used; nothing to set up by hand
-- except deploying it.
--
-- Run after multi-club.sql. Safe to run again.

DO $$
BEGIN
  CREATE EXTENSION IF NOT EXISTS pg_net;
EXCEPTION WHEN OTHERS THEN
  RAISE NOTICE 'pg_net is not available here: notifications are queued but not sent.';
END $$;

-- The Web Push keys and the Edge Function address (one row, written by the Edge Function).
CREATE TABLE IF NOT EXISTS public.push_settings (
  id integer PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  vapid_public text NOT NULL,
  vapid_private jsonb NOT NULL,
  function_url text NOT NULL CHECK (function_url ~ '^https?://'),
  created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.push_settings ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.push_settings FROM PUBLIC, anon, authenticated;

-- One row per phone or browser that turned notifications on.
CREATE TABLE IF NOT EXISTS public.push_subscriptions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  endpoint text NOT NULL UNIQUE CHECK (endpoint ~ '^https://' AND length(endpoint) <= 1000),
  p256dh text NOT NULL CHECK (length(p256dh) BETWEEN 40 AND 200),
  auth text NOT NULL CHECK (length(auth) BETWEEN 10 AND 100),
  device text NOT NULL DEFAULT '' CHECK (length(device) <= 120),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_push_subscriptions_user ON public.push_subscriptions(user_id);
ALTER TABLE public.push_subscriptions ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.push_subscriptions FROM PUBLIC, anon, authenticated;

-- Notifications waiting to be sent (and sent ones, for checking).
CREATE TABLE IF NOT EXISTS public.push_outbox (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  title text NOT NULL,
  body text NOT NULL,
  url text NOT NULL DEFAULT '',
  tag text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  sent_at timestamptz,
  error text
);
CREATE INDEX IF NOT EXISTS idx_push_outbox_created ON public.push_outbox(created_at);
ALTER TABLE public.push_outbox ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.push_outbox FROM PUBLIC, anon, authenticated;

-- ---- Signed-in people --------------------------------------------------------------
-- The public key browsers need to subscribe (null until the Edge Function made it).
CREATE OR REPLACE FUNCTION public.push_public_key()
RETURNS text LANGUAGE sql STABLE SECURITY DEFINER SET search_path = '' AS $$
  SELECT s.vapid_public FROM public.push_settings AS s WHERE s.id = 1;
$$;

CREATE OR REPLACE FUNCTION public.push_subscribe(p_endpoint text, p_p256dh text, p_auth text, p_device text DEFAULT '')
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
BEGIN
  IF (SELECT auth.uid()) IS NULL THEN RAISE EXCEPTION 'Sign in first.' USING ERRCODE = '42501'; END IF;
  INSERT INTO public.push_subscriptions (user_id, endpoint, p256dh, auth, device)
  VALUES ((SELECT auth.uid()), btrim(p_endpoint), btrim(p_p256dh), btrim(p_auth), left(coalesce(p_device, ''), 120))
  ON CONFLICT (endpoint) DO UPDATE SET user_id = EXCLUDED.user_id, p256dh = EXCLUDED.p256dh, auth = EXCLUDED.auth,
    device = EXCLUDED.device, created_at = now();
END;
$$;

CREATE OR REPLACE FUNCTION public.push_unsubscribe(p_endpoint text)
RETURNS void LANGUAGE sql SECURITY DEFINER SET search_path = '' AS $$
  DELETE FROM public.push_subscriptions WHERE endpoint = btrim(p_endpoint) AND user_id = (SELECT auth.uid());
$$;

-- Is this phone or browser on? (the website passes its own subscription address)
CREATE OR REPLACE FUNCTION public.push_status(p_endpoint text DEFAULT NULL)
RETURNS jsonb LANGUAGE sql STABLE SECURITY DEFINER SET search_path = '' AS $$
  SELECT jsonb_build_object(
    'this_device', EXISTS (SELECT 1 FROM public.push_subscriptions WHERE endpoint = p_endpoint AND user_id = (SELECT auth.uid())),
    'devices', (SELECT count(*) FROM public.push_subscriptions WHERE user_id = (SELECT auth.uid())));
$$;

-- ---- Queueing (database only) ------------------------------------------------------
CREATE OR REPLACE FUNCTION public._push_queue(p_user uuid, p_title text, p_body text, p_url text DEFAULT '', p_tag text DEFAULT '')
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_id bigint; v_url text;
BEGIN
  IF NOT EXISTS (SELECT 1 FROM public.push_subscriptions WHERE user_id = p_user) THEN RETURN; END IF;
  INSERT INTO public.push_outbox (user_id, title, body, url, tag)
  VALUES (p_user, left(p_title, 120), left(p_body, 400), coalesce(p_url, ''), left(coalesce(p_tag, ''), 60)) RETURNING id INTO v_id;
  SELECT s.function_url INTO v_url FROM public.push_settings AS s WHERE s.id = 1;
  IF v_url IS NOT NULL AND to_regnamespace('net') IS NOT NULL THEN
    BEGIN
      EXECUTE 'SELECT net.http_post(url := $1, body := $2, headers := $3)'
        USING v_url, jsonb_build_object('outbox_id', v_id), jsonb_build_object('Content-Type', 'application/json');
    EXCEPTION WHEN OTHERS THEN
      UPDATE public.push_outbox SET error = left('Could not call the push function: ' || SQLERRM, 300) WHERE id = v_id;
    END;
  END IF;
END;
$$;

-- A test notification to yourself (Settings → Send a test).
CREATE OR REPLACE FUNCTION public.push_test()
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
BEGIN
  IF (SELECT auth.uid()) IS NULL THEN RAISE EXCEPTION 'Sign in first.' USING ERRCODE = '42501'; END IF;
  IF NOT EXISTS (SELECT 1 FROM public.push_settings WHERE id = 1) THEN
    RAISE EXCEPTION 'Notifications are not set up yet. Deploy the avilonx-push Edge Function.' USING ERRCODE = '22023';
  END IF;
  PERFORM public._push_queue((SELECT auth.uid()), 'AvilonX notifications are on', 'You will get clocking and race notifications on this device.', 'index.html', 'test');
  RETURN jsonb_build_object('ok', true);
END;
$$;

-- ---- Called by the Edge Function (service role only) -----------------------------
CREATE OR REPLACE FUNCTION public.push_save_keys(p_public text, p_private jsonb, p_function_url text)
RETURNS text LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE v text;
BEGIN
  -- The first keys stay: changing them would cut off every subscribed device.
  INSERT INTO public.push_settings (id, vapid_public, vapid_private, function_url) VALUES (1, p_public, p_private, p_function_url)
  ON CONFLICT (id) DO UPDATE SET function_url = EXCLUDED.function_url;
  SELECT vapid_public INTO v FROM public.push_settings WHERE id = 1;
  RETURN v;
END;
$$;

CREATE OR REPLACE FUNCTION public.push_keys()
RETURNS jsonb LANGUAGE sql STABLE SECURITY DEFINER SET search_path = '' AS $$
  SELECT jsonb_build_object('public', s.vapid_public, 'private', s.vapid_private) FROM public.push_settings AS s WHERE s.id = 1;
$$;

-- The message and every device of its person; null once sent.
CREATE OR REPLACE FUNCTION public.push_take(p_id bigint)
RETURNS jsonb LANGUAGE sql STABLE SECURITY DEFINER SET search_path = '' AS $$
  SELECT jsonb_build_object('title', o.title, 'body', o.body, 'url', o.url, 'tag', o.tag,
    'subscriptions', coalesce((SELECT jsonb_agg(jsonb_build_object('endpoint', s.endpoint, 'p256dh', s.p256dh, 'auth', s.auth))
      FROM public.push_subscriptions AS s WHERE s.user_id = o.user_id), '[]'::jsonb))
  FROM public.push_outbox AS o WHERE o.id = p_id AND o.sent_at IS NULL AND o.created_at > now() - interval '1 day';
$$;

-- Marks the message sent and forgets devices the push service says are gone.
CREATE OR REPLACE FUNCTION public.push_done(p_id bigint, p_error text DEFAULT NULL, p_gone text[] DEFAULT '{}')
RETURNS void LANGUAGE sql SECURITY DEFINER SET search_path = '' AS $$
  DELETE FROM public.push_subscriptions WHERE endpoint = ANY (coalesce(p_gone, '{}'));
  UPDATE public.push_outbox SET sent_at = now(), error = left(p_error, 300) WHERE id = p_id;
  DELETE FROM public.push_outbox WHERE created_at < now() - interval '30 days';
$$;

REVOKE ALL ON FUNCTION public.push_public_key(), public.push_subscribe(text, text, text, text), public.push_unsubscribe(text),
  public.push_status(text), public.push_test(), public._push_queue(uuid, text, text, text, text), public.push_save_keys(text, jsonb, text),
  public.push_keys(), public.push_take(bigint), public.push_done(bigint, text, text[]) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.push_public_key(), public.push_subscribe(text, text, text, text), public.push_unsubscribe(text),
  public.push_status(text), public.push_test() TO authenticated;
GRANT EXECUTE ON FUNCTION public.push_save_keys(text, jsonb, text), public.push_keys(), public.push_take(bigint),
  public.push_done(bigint, text, text[]) TO service_role;

-- ---- What sends a notification -----------------------------------------------------
-- A pigeon is clocked: its owner, and the club's administrators and staff.
CREATE OR REPLACE FUNCTION public._push_on_clock()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE
  e public.race_entries%ROWTYPE; r public.races%ROWTYPE; m public.members%ROWTYPE;
  v_seconds numeric; v_ring text; v_detail text; v_user uuid;
BEGIN
  SELECT * INTO e FROM public.race_entries WHERE id = NEW.race_entry_id;
  IF NOT FOUND THEN RETURN NULL; END IF;
  SELECT * INTO r FROM public.races WHERE id = e.race_id;
  SELECT * INTO m FROM public.members WHERE id = e.member_id;
  v_ring := coalesce(e.pigeon_ring, NEW.pigeon_ring, 'A pigeon');
  v_seconds := CASE WHEN r.release_at_utc IS NOT NULL AND NEW.received_at_utc > r.release_at_utc THEN extract(epoch FROM NEW.received_at_utc - r.release_at_utc) END;
  v_detail := to_char(NEW.received_at_utc + interval '8 hours', 'HH12:MI:SS AM')
    || CASE WHEN v_seconds IS NOT NULL THEN ' · ' || to_char(e.distance_m * 60 / v_seconds, 'FM999,999,990.000') || ' m/min' ELSE '' END;
  FOR v_user IN SELECT p.id FROM public.app_profiles AS p WHERE p.member_id = m.id AND p.role = 'member' AND p.is_active IS NOT FALSE LOOP
    PERFORM public._push_queue(v_user, '🕊 ' || v_ring || ' was clocked', r.name || ' · ' || v_detail
      || CASE WHEN r.requires_show_up THEN E'\nBring it to the club for Show up before the race is closed.' ELSE '' END,
      'pages/member/history/index.html', 'clock-' || NEW.id);
  END LOOP;
  FOR v_user IN SELECT p.id FROM public.app_profiles AS p WHERE p.club_id = r.club_id AND p.role IN ('admin', 'staff') AND p.is_active IS NOT FALSE LOOP
    PERFORM public._push_queue(v_user, '🕊 ' || v_ring || ' · ' || coalesce(m.full_name, 'Member'), r.name || ' · ' || v_detail,
      'pages/admin/raceday/index.html', 'clock-' || NEW.id);
  END LOOP;
  RETURN NULL;
EXCEPTION WHEN OTHERS THEN
  -- A notification problem must never stop a clock from being saved.
  RAISE WARNING 'Push notification not queued: %', SQLERRM;
  RETURN NULL;
END;
$$;
REVOKE ALL ON FUNCTION public._push_on_clock() FROM PUBLIC, anon, authenticated;
DROP TRIGGER IF EXISTS zz_push_on_clock ON public.clock_events;
CREATE TRIGGER zz_push_on_clock AFTER INSERT ON public.clock_events
  FOR EACH ROW EXECUTE FUNCTION public._push_on_clock();

-- A race opens: every member of the club.
CREATE OR REPLACE FUNCTION public._push_on_race_open()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_user uuid;
BEGIN
  IF NEW.status <> 'open' OR (TG_OP = 'UPDATE' AND OLD.status = 'open') THEN RETURN NULL; END IF;
  FOR v_user IN SELECT p.id FROM public.app_profiles AS p WHERE p.club_id = NEW.club_id AND p.role = 'member' AND p.is_active IS NOT FALSE LOOP
    PERFORM public._push_queue(v_user, 'New race open: ' || NEW.name,
      'Release point: ' || NEW.release_location || coalesce(' · ' || to_char(NEW.release_at_utc + interval '8 hours', 'Mon DD, HH12:MI AM'), ''),
      'pages/member/dashboard/index.html', 'race-' || NEW.id);
  END LOOP;
  RETURN NULL;
EXCEPTION WHEN OTHERS THEN
  RAISE WARNING 'Push notification not queued: %', SQLERRM;
  RETURN NULL;
END;
$$;
REVOKE ALL ON FUNCTION public._push_on_race_open() FROM PUBLIC, anon, authenticated;
DROP TRIGGER IF EXISTS zz_push_on_race_open ON public.races;
CREATE TRIGGER zz_push_on_race_open AFTER INSERT OR UPDATE OF status ON public.races
  FOR EACH ROW EXECUTE FUNCTION public._push_on_race_open();

