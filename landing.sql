-- AvilonX Clocking: the public landing page (index.html).
--   * "Racing today": today's races of every club (club, race, release point,
--     birds clocked, best speed), readable without signing in.
--   * "Get AvilonX for your club": a request form; the Super Admin sees the
--     requests on Club accounts (and gets a push notification if turned on).
--
-- Run after multi-club.sql and push.sql. Safe to run again.

-- ---- Racing today ------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.public_races_today()
RETURNS TABLE(club_name text, race_name text, release_location text, release_at_utc timestamp without time zone,
  status text, is_practice boolean, entries bigint, clocked bigint, best_speed numeric)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = '' AS $$
  SELECT c.name::text, r.name::text, r.release_location::text, r.release_at_utc, r.status::text, r.is_practice,
    (SELECT count(*) FROM public.race_entries AS e WHERE e.race_id = r.id),
    (SELECT count(*) FROM public.race_entries AS e JOIN public.clock_events AS k ON k.race_entry_id = e.id WHERE e.race_id = r.id AND k.verification <> 'rejected'),
    (SELECT max(e.distance_m * 60 / extract(epoch FROM k.received_at_utc - r.release_at_utc))
       FROM public.race_entries AS e JOIN public.clock_events AS k ON k.race_entry_id = e.id
      WHERE e.race_id = r.id AND k.verification <> 'rejected' AND k.received_at_utc > r.release_at_utc)
  FROM public.races AS r JOIN public.clubs AS c ON c.id = r.club_id
  WHERE r.status <> 'draft' AND r.release_at_utc IS NOT NULL
    AND ((r.release_at_utc AT TIME ZONE 'UTC') AT TIME ZONE 'Asia/Manila')::date = (now() AT TIME ZONE 'Asia/Manila')::date
  ORDER BY r.release_at_utc DESC
  LIMIT 12;
$$;
REVOKE ALL ON FUNCTION public.public_races_today() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.public_races_today() TO anon, authenticated;

-- ---- Club requests -----------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.club_requests (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contact_name text NOT NULL CHECK (length(contact_name) BETWEEN 2 AND 120),
  club_name text NOT NULL CHECK (length(club_name) BETWEEN 2 AND 180),
  phone text NOT NULL DEFAULT '' CHECK (length(phone) <= 40),
  email text NOT NULL DEFAULT '' CHECK (length(email) <= 254),
  message text NOT NULL DEFAULT '' CHECK (length(message) <= 1000),
  created_at timestamptz NOT NULL DEFAULT now(),
  handled_at timestamptz
);
ALTER TABLE public.club_requests ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.club_requests FROM PUBLIC, anon, authenticated;

-- From the landing page. p_website is a hidden field people never fill (bots do).
CREATE OR REPLACE FUNCTION public.submit_club_request(p_contact_name text, p_club_name text, p_phone text, p_email text, p_message text, p_website text DEFAULT '')
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_phone text := left(btrim(coalesce(p_phone, '')), 40); v_email text := lower(left(btrim(coalesce(p_email, '')), 254)); v_id bigint; v_user uuid;
BEGIN
  IF coalesce(p_website, '') <> '' THEN RETURN jsonb_build_object('ok', true); END IF;
  IF length(btrim(coalesce(p_contact_name, ''))) < 2 OR length(btrim(coalesce(p_club_name, ''))) < 2 THEN
    RAISE EXCEPTION 'Enter your name and your club''s name.' USING ERRCODE = '22023';
  END IF;
  IF length(regexp_replace(v_phone, '\D', '', 'g')) < 7 AND v_email !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' THEN
    RAISE EXCEPTION 'Enter a phone number or an email address so we can reach you.' USING ERRCODE = '22023';
  END IF;
  IF (SELECT count(*) FROM public.club_requests WHERE created_at > now() - interval '1 hour') >= 20
     OR (SELECT count(*) FROM public.club_requests WHERE created_at > now() - interval '1 day' AND ((v_phone <> '' AND phone = v_phone) OR (v_email <> '' AND email = v_email))) >= 3 THEN
    RAISE EXCEPTION 'We already have your request. We will contact you soon.' USING ERRCODE = '22023';
  END IF;
  INSERT INTO public.club_requests (contact_name, club_name, phone, email, message)
  VALUES (left(btrim(p_contact_name), 120), left(btrim(p_club_name), 180), v_phone, v_email, left(btrim(coalesce(p_message, '')), 1000)) RETURNING id INTO v_id;
  IF to_regprocedure('public._push_queue(uuid,text,text,text,text)') IS NOT NULL THEN
    FOR v_user IN SELECT p.id FROM public.app_profiles AS p WHERE p.role = 'superadmin' LOOP
      PERFORM public._push_queue(v_user, 'New club request: ' || left(btrim(p_club_name), 60), btrim(p_contact_name) || coalesce(' · ' || nullif(v_phone, ''), ''),
        'pages/superadmin/clubs/index.html', 'club-request-' || v_id);
    END LOOP;
  END IF;
  RETURN jsonb_build_object('ok', true);
END;
$$;
REVOKE ALL ON FUNCTION public.submit_club_request(text, text, text, text, text, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.submit_club_request(text, text, text, text, text, text) TO anon, authenticated;

CREATE OR REPLACE FUNCTION public.superadmin_club_requests()
RETURNS SETOF public.club_requests LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = '' AS $$
BEGIN
  IF NOT public.is_superadmin() THEN RAISE EXCEPTION 'Super Admin only.' USING ERRCODE = '42501'; END IF;
  RETURN QUERY SELECT * FROM public.club_requests ORDER BY handled_at IS NOT NULL, created_at DESC LIMIT 100;
END;
$$;

CREATE OR REPLACE FUNCTION public.superadmin_handle_club_request(p_id bigint, p_handled boolean DEFAULT true)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
BEGIN
  IF NOT public.is_superadmin() THEN RAISE EXCEPTION 'Super Admin only.' USING ERRCODE = '42501'; END IF;
  UPDATE public.club_requests SET handled_at = CASE WHEN p_handled THEN now() END WHERE id = p_id;
END;
$$;
REVOKE ALL ON FUNCTION public.superadmin_club_requests(), public.superadmin_handle_club_request(bigint, boolean) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.superadmin_club_requests(), public.superadmin_handle_club_request(bigint, boolean) TO authenticated;

