-- AvilonX billing: clubs pay per bird encoded in a race entry.
--
-- * Every race entry saved in a (non-practice) race is counted once, at the
--   club's price at that moment. Edits are free. Deleting an entry does NOT
--   remove its count (non-refundable).
-- * The Super Admin makes a bill for a start date to end date (Philippine
--   dates, no overlap between a club's bills), marks it settled (payment
--   date, method, reference) and the invoice gets its number (AVX-2026-0001).
-- * The Super Admin can send a warning (pops up on the club admin's screen
--   until closed) and close a club account: its club admin and staff are
--   locked out until it is reopened. Members and loft readers keep clocking.
--
-- Safe to run again (part of avilonx-update.sql; it must stay the last file,
-- because it redefines current_app_role() for the lockout).

-- 1. Club settings ------------------------------------------------------------------------------
ALTER TABLE public.clubs ADD COLUMN IF NOT EXISTS bird_price numeric(10,2) NOT NULL DEFAULT 5;
ALTER TABLE public.clubs ADD COLUMN IF NOT EXISTS is_closed boolean NOT NULL DEFAULT false;
ALTER TABLE public.clubs ADD COLUMN IF NOT EXISTS closed_reason text;
ALTER TABLE public.clubs ADD COLUMN IF NOT EXISTS closed_at timestamptz;
DO $$ BEGIN IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'clubs_bird_price_range') THEN
  ALTER TABLE public.clubs ADD CONSTRAINT clubs_bird_price_range CHECK (bird_price >= 0 AND bird_price <= 10000); END IF; END $$;

-- 2. Tables ---------------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.club_bills (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  club_id bigint NOT NULL REFERENCES public.clubs(id),
  start_date date NOT NULL,
  end_date date NOT NULL,
  birds integer NOT NULL DEFAULT 0,
  amount numeric(12,2) NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  created_by uuid,
  invoice_no text UNIQUE,
  settled_at timestamptz,
  paid_on date,
  pay_method text,
  pay_reference text,
  pay_note text,
  CONSTRAINT club_bills_dates CHECK (end_date >= start_date)
);
CREATE INDEX IF NOT EXISTS club_bills_club ON public.club_bills (club_id, start_date);
ALTER TABLE public.club_bills ENABLE ROW LEVEL SECURITY;

CREATE TABLE IF NOT EXISTS public.billing_counts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  club_id bigint NOT NULL REFERENCES public.clubs(id),
  race_entry_id bigint NOT NULL UNIQUE,
  race_id bigint,
  race_name text,
  member_no text,
  member_name text,
  pigeon_ring text,
  price numeric(10,2) NOT NULL,
  encoded_at timestamptz NOT NULL DEFAULT now(),
  encoded_by uuid,
  deleted_at timestamptz,
  bill_id bigint REFERENCES public.club_bills(id)
);
CREATE INDEX IF NOT EXISTS billing_counts_club_time ON public.billing_counts (club_id, encoded_at);
ALTER TABLE public.billing_counts ENABLE ROW LEVEL SECURITY;

CREATE TABLE IF NOT EXISTS public.club_warnings (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  club_id bigint NOT NULL REFERENCES public.clubs(id),
  bill_id bigint REFERENCES public.club_bills(id) ON DELETE SET NULL,
  message text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  created_by uuid,
  seen_at timestamptz,
  seen_by uuid
);
ALTER TABLE public.club_warnings ENABLE ROW LEVEL SECURITY;

-- What happened (bills, payments, warnings, closing), for the Super Admin.
CREATE TABLE IF NOT EXISTS public.billing_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  club_id bigint NOT NULL REFERENCES public.clubs(id),
  action text NOT NULL,
  detail text,
  created_at timestamptz NOT NULL DEFAULT now(),
  created_by uuid
);
ALTER TABLE public.billing_log ENABLE ROW LEVEL SECURITY;
-- No policies: these tables are read and written only through the functions below.
REVOKE ALL ON public.club_bills, public.billing_counts, public.club_warnings, public.billing_log FROM anon, authenticated;

CREATE SEQUENCE IF NOT EXISTS public.billing_invoice_seq;

-- Philippine calendar day of a time.
CREATE OR REPLACE FUNCTION public._ph_day(p_at timestamptz)
RETURNS date LANGUAGE sql IMMUTABLE SET search_path = '' AS $$ SELECT (p_at AT TIME ZONE 'Asia/Manila')::date $$;

-- 3. Counting -------------------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public._billing_count_entry()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_race record; v_member record;
BEGIN
  SELECT r.id, r.name, r.club_id, coalesce(r.is_practice, false) AS is_practice INTO v_race FROM public.races AS r WHERE r.id = NEW.race_id;
  IF v_race.id IS NULL OR v_race.is_practice OR v_race.club_id IS NULL THEN RETURN NEW; END IF;
  SELECT m.member_no, m.full_name INTO v_member FROM public.members AS m WHERE m.id = NEW.member_id;
  INSERT INTO public.billing_counts (club_id, race_entry_id, race_id, race_name, member_no, member_name, pigeon_ring, price, encoded_by)
  SELECT v_race.club_id, NEW.id, v_race.id, v_race.name, v_member.member_no, v_member.full_name, NEW.pigeon_ring, c.bird_price, (SELECT auth.uid())
  FROM public.clubs AS c WHERE c.id = v_race.club_id
  ON CONFLICT (race_entry_id) DO NOTHING;
  RETURN NEW;
END;
$$;
CREATE OR REPLACE FUNCTION public._billing_mark_deleted()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
BEGIN
  UPDATE public.billing_counts SET deleted_at = now() WHERE race_entry_id = OLD.id AND deleted_at IS NULL;
  RETURN OLD;
END;
$$;
REVOKE ALL ON FUNCTION public._billing_count_entry(), public._billing_mark_deleted() FROM PUBLIC, anon, authenticated;
DROP TRIGGER IF EXISTS race_entries_billing_count ON public.race_entries;
CREATE TRIGGER race_entries_billing_count AFTER INSERT ON public.race_entries FOR EACH ROW EXECUTE FUNCTION public._billing_count_entry();
DROP TRIGGER IF EXISTS race_entries_billing_deleted ON public.race_entries;
CREATE TRIGGER race_entries_billing_deleted AFTER DELETE ON public.race_entries FOR EACH ROW EXECUTE FUNCTION public._billing_mark_deleted();

-- 4. Lockout: a closed club's admin and staff have no access (members keep theirs) ------------------
CREATE OR REPLACE FUNCTION public.current_app_role()
RETURNS text LANGUAGE sql STABLE SECURITY DEFINER SET search_path = '' AS $$
  SELECT p.role FROM public.app_profiles p LEFT JOIN public.clubs c ON c.id = p.club_id
  WHERE p.id = (SELECT auth.uid()) AND p.is_active AND NOT (p.role IN ('admin', 'staff') AND coalesce(c.is_closed, false))
$$;

-- Who is asking: their own profile, even when their club is closed.
CREATE OR REPLACE FUNCTION public._billing_profile()
RETURNS TABLE (role text, club_id bigint) LANGUAGE sql STABLE SECURITY DEFINER SET search_path = '' AS $$
  SELECT p.role, p.club_id FROM public.app_profiles p WHERE p.id = (SELECT auth.uid()) AND p.is_active
$$;
REVOKE ALL ON FUNCTION public._billing_profile() FROM PUBLIC, anon, authenticated;

-- The club the caller may see: any club for the Super Admin, their own for a club admin.
CREATE OR REPLACE FUNCTION public._billing_club(p_club_id bigint)
RETURNS bigint LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = '' AS $$
DECLARE v record;
BEGIN
  SELECT * INTO v FROM public._billing_profile();
  IF v.role = 'superadmin' AND p_club_id IS NOT NULL THEN RETURN p_club_id; END IF;
  IF v.role = 'admin' AND v.club_id IS NOT NULL AND (p_club_id IS NULL OR p_club_id = v.club_id) THEN RETURN v.club_id; END IF;
  RAISE EXCEPTION 'Billing is for the Super Admin and the club administrator.' USING ERRCODE = '42501';
END;
$$;
REVOKE ALL ON FUNCTION public._billing_club(bigint) FROM PUBLIC, anon, authenticated;

-- 5. Reading ------------------------------------------------------------------------------------
-- Super Admin: every club for a start date to end date.
CREATE OR REPLACE FUNCTION public.superadmin_billing_summary(p_start date, p_end date)
RETURNS TABLE (club_id bigint, club_name text, bird_price numeric, birds bigint, deleted bigint, amount numeric,
  unbilled bigint, unbilled_amount numeric, unpaid_bills bigint, unpaid_amount numeric, is_closed boolean, closed_reason text, open_warnings bigint)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = '' AS $$
BEGIN
  IF NOT public.is_superadmin() THEN RAISE EXCEPTION 'Super Admin only.' USING ERRCODE = '42501'; END IF;
  RETURN QUERY
  SELECT c.id, c.name::text, c.bird_price,
    (SELECT count(*) FROM public.billing_counts b WHERE b.club_id = c.id AND public._ph_day(b.encoded_at) BETWEEN p_start AND p_end),
    (SELECT count(*) FROM public.billing_counts b WHERE b.club_id = c.id AND b.deleted_at IS NOT NULL AND public._ph_day(b.encoded_at) BETWEEN p_start AND p_end),
    (SELECT coalesce(sum(b.price), 0) FROM public.billing_counts b WHERE b.club_id = c.id AND public._ph_day(b.encoded_at) BETWEEN p_start AND p_end),
    (SELECT count(*) FROM public.billing_counts b WHERE b.club_id = c.id AND b.bill_id IS NULL),
    (SELECT coalesce(sum(b.price), 0) FROM public.billing_counts b WHERE b.club_id = c.id AND b.bill_id IS NULL),
    (SELECT count(*) FROM public.club_bills x WHERE x.club_id = c.id AND x.settled_at IS NULL),
    (SELECT coalesce(sum(x.amount), 0) FROM public.club_bills x WHERE x.club_id = c.id AND x.settled_at IS NULL),
    c.is_closed, c.closed_reason,
    (SELECT count(*) FROM public.club_warnings w WHERE w.club_id = c.id AND w.seen_at IS NULL)
  FROM public.clubs c ORDER BY c.name;
END;
$$;

-- The encoded birds of a club for a start date to end date (the proof of a bill).
CREATE OR REPLACE FUNCTION public.billing_entries(p_club_id bigint, p_start date, p_end date)
RETURNS TABLE (id bigint, encoded_at timestamptz, race_name text, member_no text, member_name text, pigeon_ring text, price numeric, deleted boolean, bill_id bigint)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_club bigint := public._billing_club(p_club_id);
BEGIN
  RETURN QUERY SELECT b.id, b.encoded_at, b.race_name, b.member_no, b.member_name, b.pigeon_ring, b.price, b.deleted_at IS NOT NULL, b.bill_id
    FROM public.billing_counts b WHERE b.club_id = v_club AND public._ph_day(b.encoded_at) BETWEEN p_start AND p_end ORDER BY b.encoded_at, b.id LIMIT 5000;
END;
$$;

-- A club's bills, newest first.
CREATE OR REPLACE FUNCTION public.billing_bills(p_club_id bigint DEFAULT NULL)
RETURNS SETOF public.club_bills LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_club bigint := public._billing_club(p_club_id);
BEGIN
  RETURN QUERY SELECT * FROM public.club_bills b WHERE b.club_id = v_club ORDER BY b.start_date DESC;
END;
$$;

-- Club admin: settled or not, what is not billed yet, and the club's name and price.
CREATE OR REPLACE FUNCTION public.club_billing_status()
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_club bigint := public._billing_club(NULL); v_last date;
BEGIN
  SELECT max(end_date) INTO v_last FROM public.club_bills WHERE club_id = v_club;
  RETURN (SELECT jsonb_build_object(
    'club_id', c.id, 'club_name', c.name, 'bird_price', c.bird_price,
    'unpaid_bills', (SELECT count(*) FROM public.club_bills x WHERE x.club_id = c.id AND x.settled_at IS NULL),
    'unpaid_amount', (SELECT coalesce(sum(x.amount), 0) FROM public.club_bills x WHERE x.club_id = c.id AND x.settled_at IS NULL),
    'unbilled', (SELECT count(*) FROM public.billing_counts b WHERE b.club_id = c.id AND b.bill_id IS NULL),
    'unbilled_amount', (SELECT coalesce(sum(b.price), 0) FROM public.billing_counts b WHERE b.club_id = c.id AND b.bill_id IS NULL),
    'last_bill_end', v_last)
  FROM public.clubs c WHERE c.id = v_club);
END;
$$;

-- Club admin and staff: closed or not, and the warnings not closed yet (admin only).
-- Works while the club is closed (it is how the lock screen knows).
CREATE OR REPLACE FUNCTION public.club_account_status()
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = '' AS $$
DECLARE v record; c record;
BEGIN
  SELECT * INTO v FROM public._billing_profile();
  IF v.role NOT IN ('admin', 'staff') OR v.club_id IS NULL THEN RETURN jsonb_build_object('is_closed', false, 'warnings', '[]'::jsonb); END IF;
  SELECT * INTO c FROM public.clubs WHERE id = v.club_id;
  RETURN jsonb_build_object('is_closed', c.is_closed, 'closed_reason', c.closed_reason, 'club_name', c.name,
    'warnings', CASE WHEN v.role = 'admin' AND NOT c.is_closed THEN coalesce((SELECT jsonb_agg(jsonb_build_object('id', w.id, 'message', w.message, 'created_at', w.created_at) ORDER BY w.created_at)
      FROM public.club_warnings w WHERE w.club_id = c.id AND w.seen_at IS NULL), '[]'::jsonb) ELSE '[]'::jsonb END);
END;
$$;

-- Club admin closed a warning.
CREATE OR REPLACE FUNCTION public.club_dismiss_warning(p_id bigint)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_club bigint := public._billing_club(NULL);
BEGIN
  UPDATE public.club_warnings SET seen_at = now(), seen_by = (SELECT auth.uid()) WHERE id = p_id AND club_id = v_club AND seen_at IS NULL;
END;
$$;

