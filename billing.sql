CREATE OR REPLACE FUNCTION public.superadmin_set_bird_price(p_club_id bigint, p_price numeric)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
BEGIN
  PERFORM public._billing_superadmin();
  IF p_price IS NULL OR p_price < 0 OR p_price > 10000 THEN RAISE EXCEPTION 'Enter a price from 0 to 10,000.' USING ERRCODE = '22023'; END IF;
  UPDATE public.clubs SET bird_price = round(p_price, 2) WHERE id = p_club_id;
  INSERT INTO public.billing_log (club_id, action, detail, created_by) VALUES (p_club_id, 'price', 'Price per bird: ' || round(p_price, 2), (SELECT auth.uid()));
END;
$$;

-- A bill for a start date to end date: the club's birds encoded those days that are not billed yet.
CREATE OR REPLACE FUNCTION public.superadmin_create_bill(p_club_id bigint, p_start date, p_end date)
RETURNS public.club_bills LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_bill public.club_bills; v_overlap public.club_bills;
BEGIN
  PERFORM public._billing_superadmin();
  IF p_start IS NULL OR p_end IS NULL OR p_end < p_start THEN RAISE EXCEPTION 'Choose a start date and an end date (the end on or after the start).' USING ERRCODE = '22023'; END IF;
  IF p_end > public._ph_day(now()) THEN RAISE EXCEPTION 'The end date cannot be after today.' USING ERRCODE = '22023'; END IF;
  PERFORM 1 FROM public.clubs WHERE id = p_club_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Club not found.' USING ERRCODE = '22023'; END IF;
  SELECT * INTO v_overlap FROM public.club_bills b WHERE b.club_id = p_club_id AND b.start_date <= p_end AND b.end_date >= p_start LIMIT 1;
  IF v_overlap.id IS NOT NULL THEN
    RAISE EXCEPTION 'These dates overlap the bill for % to %. Start after %.', to_char(v_overlap.start_date, 'Mon DD, YYYY'), to_char(v_overlap.end_date, 'Mon DD, YYYY'), to_char(v_overlap.end_date, 'Mon DD, YYYY') USING ERRCODE = '22023';
  END IF;
  INSERT INTO public.club_bills (club_id, start_date, end_date, created_by) VALUES (p_club_id, p_start, p_end, (SELECT auth.uid())) RETURNING * INTO v_bill;
  UPDATE public.billing_counts SET bill_id = v_bill.id WHERE club_id = p_club_id AND bill_id IS NULL AND public._ph_day(encoded_at) BETWEEN p_start AND p_end;
  UPDATE public.club_bills SET birds = (SELECT count(*) FROM public.billing_counts WHERE bill_id = v_bill.id),
    amount = (SELECT coalesce(sum(price), 0) FROM public.billing_counts WHERE bill_id = v_bill.id) WHERE id = v_bill.id RETURNING * INTO v_bill;
  INSERT INTO public.billing_log (club_id, action, detail, created_by) VALUES (p_club_id, 'bill', format('Bill %s to %s: %s birds, %s', p_start, p_end, v_bill.birds, v_bill.amount), (SELECT auth.uid()));
  RETURN v_bill;
END;
$$;

-- A bill made by mistake (not settled yet): removed, its birds wait for the next bill.
CREATE OR REPLACE FUNCTION public.superadmin_delete_bill(p_bill_id bigint)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_bill public.club_bills;
BEGIN
  PERFORM public._billing_superadmin();
  SELECT * INTO v_bill FROM public.club_bills WHERE id = p_bill_id;
  IF v_bill.id IS NULL THEN RAISE EXCEPTION 'Bill not found.' USING ERRCODE = '22023'; END IF;
  IF v_bill.settled_at IS NOT NULL THEN RAISE EXCEPTION 'A settled bill cannot be removed.' USING ERRCODE = '22023'; END IF;
  UPDATE public.billing_counts SET bill_id = NULL WHERE bill_id = p_bill_id;
  DELETE FROM public.club_bills WHERE id = p_bill_id;
  INSERT INTO public.billing_log (club_id, action, detail, created_by) VALUES (v_bill.club_id, 'bill removed', format('Bill %s to %s', v_bill.start_date, v_bill.end_date), (SELECT auth.uid()));
END;
$$;

-- Payment received: the bill is settled and its invoice gets a number.
CREATE OR REPLACE FUNCTION public.superadmin_settle_bill(p_bill_id bigint, p_paid_on date, p_method text, p_reference text DEFAULT '', p_note text DEFAULT '')
RETURNS public.club_bills LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_bill public.club_bills;
BEGIN
  PERFORM public._billing_superadmin();
  SELECT * INTO v_bill FROM public.club_bills WHERE id = p_bill_id FOR UPDATE;
  IF v_bill.id IS NULL THEN RAISE EXCEPTION 'Bill not found.' USING ERRCODE = '22023'; END IF;
  IF v_bill.settled_at IS NOT NULL THEN RAISE EXCEPTION 'This bill is already settled.' USING ERRCODE = '22023'; END IF;
  IF p_paid_on IS NULL OR length(btrim(coalesce(p_method, ''))) = 0 THEN RAISE EXCEPTION 'Enter the payment date and how it was paid.' USING ERRCODE = '22023'; END IF;
  UPDATE public.club_bills SET settled_at = now(), paid_on = p_paid_on, pay_method = left(btrim(p_method), 40),
    pay_reference = nullif(left(btrim(coalesce(p_reference, '')), 80), ''), pay_note = nullif(left(btrim(coalesce(p_note, '')), 300), ''),
    invoice_no = 'AVX-' || to_char(p_paid_on, 'YYYY') || '-' || lpad(nextval('public.billing_invoice_seq')::text, 4, '0')
  WHERE id = p_bill_id RETURNING * INTO v_bill;
  INSERT INTO public.billing_log (club_id, action, detail, created_by) VALUES (v_bill.club_id, 'settled', format('%s: %s, %s %s', v_bill.invoice_no, v_bill.amount, v_bill.pay_method, coalesce(v_bill.pay_reference, '')), (SELECT auth.uid()));
  RETURN v_bill;
END;
$$;

CREATE OR REPLACE FUNCTION public.superadmin_send_warning(p_club_id bigint, p_message text, p_bill_id bigint DEFAULT NULL)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
BEGIN
  PERFORM public._billing_superadmin();
  IF length(btrim(coalesce(p_message, ''))) < 3 THEN RAISE EXCEPTION 'Write the warning message.' USING ERRCODE = '22023'; END IF;
  INSERT INTO public.club_warnings (club_id, bill_id, message, created_by) VALUES (p_club_id, p_bill_id, left(btrim(p_message), 1000), (SELECT auth.uid()));
  INSERT INTO public.billing_log (club_id, action, detail, created_by) VALUES (p_club_id, 'warning', left(btrim(p_message), 300), (SELECT auth.uid()));
END;
$$;

CREATE OR REPLACE FUNCTION public.superadmin_billing_warnings(p_club_id bigint)
RETURNS SETOF public.club_warnings LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = '' AS $$
BEGIN
  PERFORM public._billing_superadmin();
  RETURN QUERY SELECT * FROM public.club_warnings WHERE club_id = p_club_id ORDER BY created_at DESC LIMIT 50;
END;
$$;

-- Close (lock out the club admin and staff) or reopen a club account.
CREATE OR REPLACE FUNCTION public.superadmin_set_club_closed(p_club_id bigint, p_closed boolean, p_reason text DEFAULT '')
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
BEGIN
  PERFORM public._billing_superadmin();
  IF p_closed AND length(btrim(coalesce(p_reason, ''))) < 3 THEN RAISE EXCEPTION 'Write the reason (the club admin sees it).' USING ERRCODE = '22023'; END IF;
  UPDATE public.clubs SET is_closed = p_closed, closed_reason = CASE WHEN p_closed THEN left(btrim(p_reason), 500) END,
    closed_at = CASE WHEN p_closed THEN now() END WHERE id = p_club_id;
  INSERT INTO public.billing_log (club_id, action, detail, created_by)
    VALUES (p_club_id, CASE WHEN p_closed THEN 'closed' ELSE 'reopened' END, nullif(left(btrim(coalesce(p_reason, '')), 300), ''), (SELECT auth.uid()));
END;
$$;

CREATE OR REPLACE FUNCTION public.superadmin_billing_log(p_club_id bigint)
RETURNS SETOF public.billing_log LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = '' AS $$
BEGIN
  PERFORM public._billing_superadmin();
  RETURN QUERY SELECT * FROM public.billing_log WHERE club_id = p_club_id ORDER BY created_at DESC LIMIT 100;
END;
$$;

