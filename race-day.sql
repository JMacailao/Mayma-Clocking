-- AvilonX Clocking: race day tools.
--
-- - Change history: every change to races, race entries, clocks and bonded
--   birds is recorded (who, when, before and after). Club admins and staff
--   read their club's history on the Change history page.
-- - Practice races: races.is_practice (the column is added by
--   entry-remarks.sql, which also leaves practice races out of the public
--   results).
-- - Live updates: clocks are sent to open pages at once (Supabase Realtime),
--   so a member's result pops up the moment the reader is tapped.
-- - setup_status(): which setup files have been run (Super Admin → Setup).
--
-- Run after all the other files (avilonx-update.sql already does). Safe to
-- run again.

ALTER TABLE public.races ADD COLUMN IF NOT EXISTS is_practice boolean NOT NULL DEFAULT false;

-- ---- Change history ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.audit_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  club_id bigint REFERENCES public.clubs(id) ON DELETE CASCADE,
  table_name text NOT NULL,
  row_id bigint,
  action text NOT NULL CHECK (action IN ('insert', 'update', 'delete')),
  changed_by uuid,
  changed_by_name text,
  changed_at timestamptz NOT NULL DEFAULT now(),
  old_data jsonb,
  new_data jsonb
);
CREATE INDEX IF NOT EXISTS idx_audit_log_club_time ON public.audit_log (club_id, changed_at DESC);

ALTER TABLE public.audit_log ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS audit_log_club_read ON public.audit_log;
CREATE POLICY audit_log_club_read ON public.audit_log FOR SELECT TO authenticated
  USING (public.can_manage_club_data() AND club_id = public.current_club_id());
REVOKE ALL ON public.audit_log FROM anon, PUBLIC;
GRANT SELECT ON public.audit_log TO authenticated;

CREATE OR REPLACE FUNCTION public._audit_change()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE
  v_row jsonb := CASE WHEN TG_OP = 'DELETE' THEN to_jsonb(OLD) ELSE to_jsonb(NEW) END;
  v_club bigint;
  v_name text;
BEGIN
  -- Skip updates that change nothing.
  IF TG_OP = 'UPDATE' AND to_jsonb(OLD) = to_jsonb(NEW) THEN RETURN NULL; END IF;
  v_club := nullif(v_row->>'club_id', '')::bigint;
  IF v_club IS NULL AND v_row ? 'race_id' THEN
    SELECT r.club_id INTO v_club FROM public.races AS r WHERE r.id = (v_row->>'race_id')::bigint;
  END IF;
  IF v_club IS NULL AND v_row ? 'race_entry_id' THEN
    SELECT r.club_id INTO v_club FROM public.race_entries AS e JOIN public.races AS r ON r.id = e.race_id
    WHERE e.id = (v_row->>'race_entry_id')::bigint;
  END IF;
  SELECT p.username INTO v_name FROM public.app_profiles AS p WHERE p.id = auth.uid();
  INSERT INTO public.audit_log (club_id, table_name, row_id, action, changed_by, changed_by_name, old_data, new_data)
  VALUES (v_club, TG_TABLE_NAME, nullif(v_row->>'id', '')::bigint, lower(TG_OP), auth.uid(),
    coalesce(v_name, CASE WHEN auth.uid() IS NULL THEN 'RFID reader / system' ELSE 'Unknown account' END),
    CASE WHEN TG_OP = 'INSERT' THEN NULL ELSE to_jsonb(OLD) END,
    CASE WHEN TG_OP = 'DELETE' THEN NULL ELSE to_jsonb(NEW) END);
  RETURN NULL;
END;
$$;
REVOKE ALL ON FUNCTION public._audit_change() FROM PUBLIC, anon, authenticated;

DO $$
DECLARE
  v_table text;
BEGIN
  FOREACH v_table IN ARRAY ARRAY['races', 'race_entries', 'clock_events', 'pigeons'] LOOP
    IF to_regclass('public.' || v_table) IS NOT NULL THEN
      EXECUTE format('DROP TRIGGER IF EXISTS zz_audit_change ON public.%I', v_table);
      EXECUTE format('CREATE TRIGGER zz_audit_change AFTER INSERT OR UPDATE OR DELETE ON public.%I FOR EACH ROW EXECUTE FUNCTION public._audit_change()', v_table);
    END IF;
  END LOOP;
END $$;

-- ---- Live updates (Supabase Realtime) --------------------------------------------
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_publication WHERE pubname = 'supabase_realtime')
     AND NOT EXISTS (SELECT 1 FROM pg_publication_tables WHERE pubname = 'supabase_realtime' AND schemaname = 'public' AND tablename = 'clock_events') THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.clock_events;
  END IF;
END $$;

-- ---- Setup status ------------------------------------------------------------------
-- Which setup files have been run, for the Super Admin's Setup page.
CREATE OR REPLACE FUNCTION public.setup_status()
RETURNS jsonb LANGUAGE sql STABLE SECURITY DEFINER SET search_path = '' AS $$
  SELECT jsonb_build_object(
    'multi-club', to_regclass('public.clubs') IS NOT NULL,
    'account-credentials', EXISTS (SELECT 1 FROM pg_proc AS p JOIN pg_namespace AS n ON n.oid = p.pronamespace WHERE n.nspname = 'public' AND p.proname = 'admin_update_user_credentials'),
    'public-results', EXISTS (SELECT 1 FROM pg_proc AS p JOIN pg_namespace AS n ON n.oid = p.pronamespace WHERE n.nspname = 'public' AND p.proname = 'public_race_results'),
    'sticker-barcodes', to_regclass('public.barcode_stickers') IS NOT NULL,
    'race-release-time', EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'races_open_requires_release_time'),
    'race-schedule-dates', EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'races' AND column_name = 'open_date'),
    'nfc-tags', to_regclass('public.nfc_tags') IS NOT NULL,
    'rfid-devices', to_regclass('public.rfid_devices') IS NOT NULL,
    'entry-remarks', to_regclass('public.entry_remark_options') IS NOT NULL,
    'bird-bonding', to_regclass('public.pigeons') IS NOT NULL,
    'show-up', EXISTS (SELECT 1 FROM pg_proc AS p JOIN pg_namespace AS n ON n.oid = p.pronamespace WHERE n.nspname = 'public' AND p.proname = 'clock_is_disqualified'),
    'rfid-tag-in-use', EXISTS (SELECT 1 FROM pg_proc AS p JOIN pg_namespace AS n ON n.oid = p.pronamespace WHERE n.nspname = 'public' AND p.proname = 'require_rfid_tag_free'),
    'race-tag-expiry', EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'races' AND column_name = 'nfc_expiry_days'),
    'bird-ring-only', EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'pigeons' AND column_name = 'bond_type'),
    'race-day', to_regclass('public.audit_log') IS NOT NULL,
    'realtime', EXISTS (SELECT 1 FROM pg_publication_tables WHERE pubname = 'supabase_realtime' AND schemaname = 'public' AND tablename = 'clock_events')
  );
$$;
REVOKE ALL ON FUNCTION public.setup_status() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.setup_status() TO authenticated;

